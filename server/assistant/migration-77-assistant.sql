-- (25) the same supplier bill entered twice (same supplier, same bill number and amount), and the same party and amount
-- within three days under another number (src/js/06-audit.js dup)
create or replace function public.asst_duplicates(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('duplicates'); end if;
  with led as (select * from asst_led(p_client, s.bk)),
  v as (select v.guid, v.day, v.vno, v.vtype, v.ref, regexp_replace(upper(coalesce(v.ref, '')), '[^A-Z0-9]', '', 'g') nref,
          (select l.ledger from tally_lines l join led on led.name = l.ledger and (led.creditor or led.gstin <> '') where l.book_id = s.bk and l.guid = v.guid and l.amount > 0 order by l.amount desc limit 1) party,
          (select max(l.amount) from tally_lines l join led on led.name = l.ledger and (led.creditor or led.gstin <> '') where l.book_id = s.bk and l.guid = v.guid and l.amount > 0) amt
          from tally_vouchers v where v.book_id = s.bk and v.day between s.d_from and s.d_to and not v.cancelled and not v.optional and v.deleted_at is null and v.vtype !~* 'sales|receipt|payment|contra'),
  p as (select * from v where v.party is not null),
  d1 as (select p.*, first_value(p.vno) over w first_no, first_value(p.day) over w first_day, row_number() over w rn from p
          where length(p.nref) >= 3 and p.ref !~ '^\s*\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}\s*$' window w as (partition by p.party, p.nref, round(p.amt) order by p.day, p.vno)),
  d2 as (select p.*, lag(p.vno) over w prev_no, lag(p.day) over w prev_day, lag(p.nref) over w prev_ref from p window w as (partition by p.party, p.amt order by p.day, p.vno)),
  r as (select 'same bill entered twice' kind, d1.guid, d1.day, d1.vno, d1.party, d1.ref, d1.amt, 'same bill ' || d1.ref || ' as voucher ' || d1.first_no || ' of ' || to_char(d1.first_day, 'DD-Mon-YYYY') note from d1 where d1.rn > 1
        union all
        select 'same party and amount within 3 days', d2.guid, d2.day, d2.vno, d2.party, d2.ref, d2.amt, 'same party and amount as voucher ' || d2.prev_no || ' of ' || to_char(d2.prev_day, 'DD-Mon-YYYY') from d2
         where d2.prev_day is not null and d2.day - d2.prev_day <= 3 and d2.nref is distinct from d2.prev_ref and d2.amt >= 5000)
  select jsonb_build_object('tool', 'duplicates', 'title', 'Possible duplicate entries', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'columns', jsonb_build_array(asst_col('kind', 'Check'), asst_col('day', 'Date', 'date'), asst_col('vno', 'No.'), asst_col('party', 'Supplier'), asst_col('ref', 'Bill no.'), asst_col('amount', 'Amount', 'amount'), asst_col('note', 'Note')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', r.guid, 'kind', r.kind, 'day', r.day, 'vno', r.vno, 'party', r.party, 'ref', r.ref, 'amount', round(r.amt, 2), 'note', r.note) order by r.kind desc, r.day), '[]'::jsonb),
    'summary', jsonb_build_object('sameBill', count(*) filter (where r.kind = 'same bill entered twice'), 'near', count(*) filter (where r.kind <> 'same bill entered twice'), 'amount', round(coalesce(sum(r.amt) filter (where r.kind = 'same bill entered twice'), 0), 2)))
    into res from r;
  return res;
end $$;

-- (26) round-sum journals of p_min or more to income or expense ledgers, and such journals with no narration
create or replace function public.asst_round_sums(p_client text, p_from date, p_to date, p_min numeric default 100000)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; mn numeric := greatest(coalesce(p_min, 100000), 1000);
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('round_sums'); end if;
  with led as (select * from asst_led(p_client, s.bk)),
  j as (select e.guid, min(e.day) as day, min(e.vno) vno, min(e.party) party, min(e.narration) narr, sum(case when e.amount > 0 then e.amount else 0 end) amt, bool_or(coalesce(led.expense or led.income, false)) pl
          from asst_entries(s.bk, s.d_from, s.d_to) e left join led on led.name = e.ledger where e.vtype ~* 'journal' group by e.guid),
  r as (select j.*, case when j.pl and j.amt % 10000 = 0 then 'round sum to income or expense' else 'no narration' end kind from j
         where j.amt >= mn and ((j.pl and j.amt % 10000 = 0) or btrim(coalesce(j.narr, '')) = ''))
  select jsonb_build_object('tool', 'round_sums', 'title', 'Round-sum journals of ' || to_char(mn, 'FM99,99,99,990') || ' or more', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
