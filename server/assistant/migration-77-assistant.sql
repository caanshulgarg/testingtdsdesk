-- the user ticks a document as attached (or not)
create or replace function public.asst_notice_tick(p_id uuid, p_item text, p_done boolean)
returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare n public.assistant_notices%rowtype;
begin
  if not public.can_write() then raise exception 'only the firm''s owner and staff change a notice'; end if;
  update assistant_notices a set checklist = (select coalesce(jsonb_agg(case when x->>'id' = p_item then x || jsonb_build_object('done', coalesce(p_done, false)) else x end order by o), '[]'::jsonb)
                                              from jsonb_array_elements(a.checklist) with ordinality t(x, o)), updated_at = now()
   where a.id = p_id and a.firm_id = my_firm() returning * into n;
  if n.id is null then raise exception 'no such notice'; end if;
  insert into assistant_notice_events (notice_id, firm_id, by_user, what) values (n.id, n.firm_id, auth.uid(), left((case when p_done then 'attached: ' else 'not attached: ' end) || p_item, 200));
  return to_jsonb(n);
end $$;
-- the user marks the reply drafted or filed (filed needs the acknowledgement number); FinCom files nothing
create or replace function public.asst_notice_status(p_id uuid, p_status text, p_ack text default null, p_filed_on date default null)
returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare n public.assistant_notices%rowtype;
