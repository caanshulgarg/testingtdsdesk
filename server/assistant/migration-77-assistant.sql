-- the best ledger for words typed ("hdfc bank", "rent"): the same name, else every word in it, the shortest first
create or replace function public.asst_match_ledger(p_book uuid, p_text text)
returns text language sql stable security invoker set search_path = public, pg_temp as $$
  with w as (select array_remove(regexp_split_to_array(lower(btrim(coalesce(p_text, ''))), '\s+'), '') as ws)
  select l.name from tally_ledgers l, w
   where l.book_id = p_book and l.merged_into is null and l.deleted_at is null and coalesce(p_text, '') <> ''
     and (lower(l.name) = lower(btrim(p_text)) or not exists (select 1 from unnest(w.ws) x where position(x in lower(l.name)) = 0))
   order by (lower(l.name) = lower(btrim(p_text))) desc, length(l.name), l.name limit 1
$$;

