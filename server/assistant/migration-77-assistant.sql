-- (19) input tax in the books against GSTR-2B, month by month and supplier by supplier. Books: the input GST lines (not
-- reverse charge) of each entry, under the entry's supplier GSTIN, in the month of the entry; 2B: the 2Bs brought into
-- FinCom (client_book_items "twoBs", as the 2B page keeps them), by supplier GSTIN
create or replace function public.asst_itc_vs_2b(p_client text, p_from date, p_to date, p_gstin text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; reg text := upper(coalesce(p_gstin, ''));
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('itc_vs_2b'); end if;
  with led as (select * from asst_led(p_client, s.bk)),
  bk as (select to_char(e.day, 'YYYYMM') ym, coalesce(nullif(e.gstin, ''), '(no GSTIN)') gstin, min(e.party) party, -sum(e.amount) tax, count(distinct e.guid) docs
           from asst_entries(s.bk, s.d_from, s.d_to) e join led on led.name = e.ledger and led.kind = 'gst' and led.side = 'input' and led.what in ('gst', 'gst_import')
           join tally_vouchers v on v.book_id = s.bk and v.guid = e.guid
          where (reg = '' or upper(coalesce(v.cmp_gstin, '')) = reg) and not coalesce(v.gst_rcm, false)
            and not exists (select 1 from asst_entries(s.bk, e.day, e.day) z join led zl on zl.name = z.ledger and zl.what = 'gst_rcm' where z.guid = e.guid)
          group by 1, 2),
  tb as (select i.item, i.data from client_book_items i where i.client_id = p_client and i.key = 'twoBs' and i.item like '.%' and not i.deleted
           and (reg = '' or upper(split_part(substr(i.item, 2), '|', 1)) = reg)),
  r2b as (select coalesce(nullif(r->>'ym', ''), t.data->>'ym') ym, upper(coalesce(nullif(r->>'gstin', ''), nullif(r->>'ctin', ''), split_part(r->>'key', '|', 3))) gstin, min(coalesce(r->>'party', r->>'trdnm', '')) party,
            sum((coalesce((r->>'igst')::numeric, 0) + coalesce((r->>'cgst')::numeric, 0) + coalesce((r->>'sgst')::numeric, 0) + coalesce((r->>'cess')::numeric, 0)) * case when coalesce(r->>'sec', '') ~* 'cdn' and coalesce(r->>'typ', '') = 'C' then -1 else 1 end) tax,
            count(*) docs, array_agg(regexp_replace(upper(coalesce(r->>'noN', r->>'no', '')), '[^A-Z0-9]', '', 'g')) nos
           from tb t cross join lateral jsonb_array_elements(coalesce(t.data->'rows', '[]'::jsonb)) r
          where not coalesce((r->>'rcm')::boolean, false) group by 1, 2),
  months as (select distinct ym from (select ym from bk union select ym from r2b) z where to_date(ym, 'YYYYMM') between date_trunc('month', s.d_from) and s.d_to),
  j as (select coalesce(bk.ym, r2b.ym) ym, coalesce(bk.gstin, r2b.gstin) gstin, coalesce(nullif(bk.party, ''), r2b.party, '') party, coalesce(bk.tax, 0) books, coalesce(r2b.tax, 0) twob, coalesce(bk.docs, 0) bdocs, coalesce(r2b.docs, 0) tdocs, r2b.nos
          from bk full join r2b on r2b.ym = bk.ym and r2b.gstin = bk.gstin where coalesce(bk.ym, r2b.ym) in (select ym from months)),
  have as (select distinct coalesce(t.data->>'ym', '') ym from tb t)
  select jsonb_build_object('tool', 'itc_vs_2b', 'title', 'Input tax: books against GSTR-2B', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'books: input GST lines of each entry (not reverse charge) in the month of the entry, by the supplier''s GSTIN; 2B: the 2Bs brought into FinCom; a month with no 2B shows 2B nil',
    'months2b', coalesce((select jsonb_agg(ym order by ym) from have where ym <> ''), '[]'::jsonb),
    'columns', jsonb_build_array(asst_col('month', 'Month'), asst_col('gstin', 'Supplier GSTIN'), asst_col('party', 'Supplier'), asst_col('books', 'In books', 'amount'), asst_col('twob', 'In 2B', 'amount'), asst_col('diff', 'Books less 2B', 'amount'), asst_col('note', 'Note')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('month', to_char(to_date(j.ym, 'YYYYMM'), 'Mon-YYYY'), 'ym', j.ym, 'gstin', j.gstin, 'party', j.party, 'books', round(j.books, 2), 'twob', round(j.twob, 2), 'diff', round(j.books - j.twob, 2),
        'note', case when j.ym not in (select ym from have) then 'no 2B for the month in FinCom' when j.twob = 0 then 'not in 2B' when j.books = 0 then 'in 2B, not in the books this month' || coalesce(' (in the books in ' || (select string_agg(distinct to_char(v.day, 'Mon-YYYY') || ', entry ' || v.vno, '; ') from tally_vouchers v
            where v.book_id = s.bk and upper(v.gstin) = j.gstin and regexp_replace(upper(v.ref), '[^A-Z0-9]', '', 'g') = any(coalesce(j.nos, '{}')) and to_char(v.day, 'YYYYMM') <> j.ym and not v.cancelled and v.deleted_at is null) || ')', '') when abs(j.books - j.twob) < 1 then 'agrees' else 'differs' end)
        order by j.ym, abs(j.books - j.twob) desc, j.gstin) filter (where abs(j.books - j.twob) >= 1 or true), '[]'::jsonb),
    'summary', jsonb_build_object('books', round(coalesce(sum(j.books), 0), 2), 'twob', round(coalesce(sum(j.twob), 0), 2), 'diff', round(coalesce(sum(j.books - j.twob), 0), 2),
       'byMonth', coalesce((select jsonb_object_agg(z.ym, jsonb_build_object('books', z.b, 'twob', z.t, 'diff', z.b - z.t)) from (select j2.ym, round(sum(j2.books), 2) b, round(sum(j2.twob), 2) t from j j2 group by j2.ym) z), '{}'::jsonb)))
    into res from j;
  return res;
end $$;

-- (20) sales in the books against GSTR-1 as filed (gst_returns R1, fetched from the portal), month by month
create or replace function public.asst_sales_vs_r1(p_client text, p_from date, p_to date, p_gstin text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; regs text[];
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('sales_vs_r1'); end if;
  select array_agg(distinct upper(g)) into regs from (select v.cmp_gstin g from tally_vouchers v where v.book_id = s.bk and coalesce(v.cmp_gstin, '') <> ''
                                                       union select c.gstin from clients c where c.id = p_client and coalesce(c.gstin, '') <> '') z
   where coalesce(p_gstin, '') = '' or upper(g) = upper(p_gstin);
  with led as (select * from asst_led(p_client, s.bk)),
  bk as (select to_char(e.day, 'YYYYMM') ym, upper(coalesce(v.cmp_gstin, '')) reg,
           sum(case when led.sales or (led.income and not led.duties) then e.amount else 0 end) taxable,
           sum(case when led.kind = 'gst' and led.side = 'output' and led.what = 'gst' then e.amount else 0 end) tax
           from asst_entries(s.bk, s.d_from, s.d_to) e join led on led.name = e.ledger join tally_vouchers v on v.book_id = s.bk and v.guid = e.guid
          where exists (select 1 from tally_lines x join led sl on sl.name = x.ledger and sl.sales where x.book_id = s.bk and x.guid = e.guid) group by 1, 2),
  r1 as (select substr(g.period, 3, 4) || substr(g.period, 1, 2) ym, upper(g.gstin) reg,
           coalesce((select sum(coalesce((d->>'txval')::numeric, 0)) from jsonb_path_query(g.data, 'strict $.**.itm_det') d), 0) taxable,
           coalesce((select sum(coalesce((d->>'iamt')::numeric, 0) + coalesce((d->>'camt')::numeric, 0) + coalesce((d->>'samt')::numeric, 0) + coalesce((d->>'csamt')::numeric, 0)) from jsonb_path_query(g.data, 'strict $.**.itm_det') d), 0) tax
           from gst_returns g where g.form = 'R1' and g.status = 'ok' and upper(g.gstin) = any(coalesce(regs, '{}'))),
  j as (select coalesce(bk.ym, r1.ym) ym, coalesce(bk.reg, r1.reg) reg, coalesce(bk.taxable, 0) bt, coalesce(bk.tax, 0) btax, r1.taxable rt, r1.tax rtax
          from bk full join r1 on r1.ym = bk.ym and r1.reg = bk.reg where to_date(coalesce(bk.ym, r1.ym), 'YYYYMM') between date_trunc('month', s.d_from) and s.d_to)
  select jsonb_build_object('tool', 'sales_vs_r1', 'title', 'Sales: books against GSTR-1 filed', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'books: sales entries (taxable value and output GST); GSTR-1: the returns fetched from the portal into FinCom (all tables, items'' taxable value and tax)',
    'columns', jsonb_build_array(asst_col('month', 'Month'), asst_col('gstin', 'GSTIN'), asst_col('books', 'Taxable in books', 'amount'), asst_col('r1', 'Taxable in GSTR-1', 'amount'), asst_col('diff', 'Difference', 'amount'), asst_col('btax', 'Tax in books', 'amount'), asst_col('rtax', 'Tax in GSTR-1', 'amount'), asst_col('note', 'Note')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('month', to_char(to_date(j.ym, 'YYYYMM'), 'Mon-YYYY'), 'gstin', j.reg, 'books', round(j.bt, 2), 'r1', round(j.rt, 2), 'diff', case when j.rt is null then null else round(j.bt - j.rt, 2) end,
        'btax', round(j.btax, 2), 'rtax', round(j.rtax, 2), 'note', case when j.rt is null then 'no GSTR-1 on file in FinCom' when abs(j.bt - j.rt) < 1 and abs(j.btax - j.rtax) < 1 then 'agrees' else 'differs' end) order by j.ym, j.reg), '[]'::jsonb),
    'summary', jsonb_build_object('months', count(*), 'withR1', count(*) filter (where j.rt is not null), 'differ', count(*) filter (where j.rt is not null and (abs(j.bt - j.rt) >= 1 or abs(j.btax - j.rtax) >= 1))))
    into res from j;
  return res;
end $$;

-- (21) reverse charge: each entry with reverse-charge GST, the value and the tax
create or replace function public.asst_rcm(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('rcm'); end if;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  r as (select e.guid, min(e.day) as day, min(e.vno) vno, min(e.party) party,
          sum(case when led.what = 'gst_rcm' and led.side <> 'input' then e.amount else 0 end) tax,
          -sum(case when led.expense or led.purchase or led.fixed then e.amount else 0 end) as value
          from e join led on led.name = e.ledger group by e.guid having sum(case when led.what = 'gst_rcm' and led.side <> 'input' then e.amount else 0 end) > 0 and sum(case when led.expense or led.purchase or led.fixed then e.amount else 0 end) < 0)
  select jsonb_build_object('tool', 'rcm', 'title', 'Reverse charge entries', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'columns', jsonb_build_array(asst_col('day', 'Date', 'date'), asst_col('vno', 'No.'), asst_col('party', 'Supplier'), asst_col('value', 'Value', 'amount'), asst_col('tax', 'Tax payable (RCM)', 'amount')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', r.guid, 'day', r.day, 'vno', r.vno, 'party', r.party, 'value', round(r.value, 2), 'tax', round(r.tax, 2)) order by r.day, r.vno), '[]'::jsonb),
    'summary', jsonb_build_object('value', round(coalesce(sum(r.value), 0), 2), 'tax', round(coalesce(sum(r.tax), 0), 2), 'entries', count(*)))
    into res from r;
  return res;
end $$;

