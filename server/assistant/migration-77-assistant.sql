-- the version of a client's books as the user sees them: changes whenever the bridge brings anything in or the ledger list
-- or the client's other book items change
create or replace function public.asst_data_version(p_client text)
returns text language sql stable security invoker set search_path = public, pg_temp as $$
  select md5(coalesce((select string_agg(b.book_id::text || '|' || coalesce(b.days_at::text, '') || '|' || coalesce(b.ledgers_at::text, '') || '|' || coalesce(b.state_at::text, '') || '|' ||
           coalesce((select max(v.alter_id)::text || ':' || count(*)::text from tally_vouchers v where v.book_id = b.book_id), ''), ',' order by b.book_id) from tally_books b where b.client_id = p_client), '') || '#' ||
         coalesce((select max(i.seq)::text || ':' || max(i.updated_at)::text from client_book_items i where i.client_id = p_client), ''))
$$;

