-- every asst_ function: the signed-in members of a firm only (never anon); as the caller (security invoker)
do $$
declare f record;
begin
  for f in select p.oid::regprocedure sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.proname like 'asst\_%' and p.proname not in ('asst_cap_take', 'asst_cost_add', 'asst_log_add', 'asst_usage', 'asst_set_cap') loop
    execute format('revoke all on function %s from public, anon', f.sig);
    execute format('grant execute on function %s to authenticated', f.sig);
  end loop;
end $$;

