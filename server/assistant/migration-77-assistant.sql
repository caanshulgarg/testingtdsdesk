-- (29) the due list: TDS deposits (each month's deductions, due the 7th, 30 April for March) and whether paid, GSTR-1 on
-- the 11th and GSTR-3B on the 20th of each month (filed when FinCom holds the return from the portal), TDS returns each
-- quarter, and the tasks added from notices
create or replace function public.asst_due_list(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; today date := (now() at time zone 'Asia/Kolkata')::date; regs text[];
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('due_list'); end if;
  select array_agg(distinct upper(v.cmp_gstin)) into regs from tally_vouchers v where v.book_id = s.bk and coalesce(v.cmp_gstin, '') <> '';
  with tds as (select t.ym, sum(t.deducted) amt, min(t.due) due, bool_and(t.paid_on is not null) paid, max(t.paid_on) paid_on from asst_tds_paid(p_client, s.bk, s.d_from, s.d_to) t where t.vno <> 'opening' group by t.ym),
  mo as (select gs::date m from generate_series(date_trunc('month', s.d_from), date_trunc('month', s.d_to), interval '1 month') gs),
  gst as (select r.reg, mo.m, f.form, (mo.m + interval '1 month')::date + case when f.form = 'R1' then 10 else 19 end due,
            exists (select 1 from gst_returns g where upper(g.gstin) = r.reg and g.form = f.form and g.period = to_char(mo.m, 'MMYYYY') and g.status = 'ok') filed
            from unnest(coalesce(regs, '{}')) r(reg) cross join mo cross join (values ('R1'), ('3B')) f(form)),
  q as (select * from (values (4, 7, 31, 'Q1'), (7, 10, 31, 'Q2'), (10, 1, 31, 'Q3'), (1, 5, 31, 'Q4')) z(qm, dm, dd, qn)),
  tr as (select distinct q.qn, make_date(case when q.dm < extract(month from mo.m)::int or (q.qn = 'Q4') then extract(year from mo.m)::int + case when q.qn = 'Q3' then 1 else 0 end else extract(year from mo.m)::int end, q.dm, q.dd) due
           from mo join q on extract(month from mo.m)::int between q.qm and q.qm + 2 where exists (select 1 from tds)),
  it as (select 'TDS deposit for ' || to_char(to_date(tds.ym, 'YYYYMM'), 'Mon-YYYY') what, tds.due, tds.amt amount, case when tds.paid then 'paid ' || to_char(tds.paid_on, 'DD-Mon-YYYY') when tds.due < today then 'overdue' else 'due' end status from tds
         union all select case when g.form = 'R1' then 'GSTR-1 ' else 'GSTR-3B ' end || to_char(g.m, 'Mon-YYYY') || ' (' || g.reg || ')', g.due, null, case when g.filed then 'filed (return on file)' when g.due < today then 'not on file' else 'due' end from gst g
         union all select 'TDS return ' || tr.qn, tr.due, null, case when tr.due < today then 'check on the TDS page' else 'due' end from tr
         union all select 'Task: ' || t.title, t.due, null, case when t.done then 'done' when t.due < today then 'overdue' else 'due' end from client_due_tasks t where t.client_id = p_client)
  select jsonb_build_object('tool', 'due_list', 'title', 'Due list', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to), 'today', today,
    'basis', 'TDS deposits from the books; a GST return is "filed" when FinCom holds it from the portal; the TDS and GST pages have the full status',
    'columns', jsonb_build_array(asst_col('due', 'Due', 'date'), asst_col('what', 'What'), asst_col('amount', 'Amount', 'amount'), asst_col('status', 'Status')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('due', it.due, 'what', it.what, 'amount', round(it.amount, 2), 'status', it.status) order by it.due, it.what), '[]'::jsonb),
    'summary', jsonb_build_object('overdue', count(*) filter (where it.status in ('overdue', 'not on file'))))
    into res from it;
  return res;
end $$;

-- (30) turnover and the tax-audit limits (section 44AB): revenue from operations, and the share of cash receipts and cash
-- payments (the 10 crore limit needs both at 5% or less)
create or replace function public.asst_turnover(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; rev numeric; oth numeric; cin numeric; cout numeric; rin numeric; pout numeric;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('turnover'); end if;
  with led as (select * from asst_led(p_client, s.bk))
  select coalesce(sum(d.amount) filter (where led.sales or led.mis = 'rev'), 0), coalesce(sum(d.amount) filter (where led.mis = 'oth'), 0) into rev, oth
    from tally_ledger_day d join led on led.name = d.ledger where d.book_id = s.bk and d.day between s.d_from and s.d_to;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  v as (select e.guid, sum(case when led.cash and e.amount < 0 then -e.amount else 0 end) ci, sum(case when led.cash and e.amount > 0 then e.amount else 0 end) co,
          sum(case when (led.cash or led.bank) and e.amount < 0 then -e.amount else 0 end) ri, sum(case when (led.cash or led.bank) and e.amount > 0 then e.amount else 0 end) po,
          bool_or(coalesce(led.cash and led.bank, false)) x, count(*) filter (where led.cash or led.bank) cb, count(*) n from e left join led on led.name = e.ledger group by e.guid)
  select coalesce(sum(ci) filter (where cb < n), 0), coalesce(sum(co) filter (where cb < n), 0), coalesce(sum(ri) filter (where cb < n), 0), coalesce(sum(po) filter (where cb < n), 0) into cin, cout, rin, pout from v;
  return jsonb_build_object('tool', 'turnover', 'title', 'Turnover and the tax-audit limits', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'revenue from operations: Sales Accounts and Direct Incomes, before GST; receipts and payments: cash and bank lines of every entry except transfers between cash and bank',
    'columns', jsonb_build_array(asst_col('what', ''), asst_col('amount', 'Amount', 'amount'), asst_col('pct', 'Share %', 'pct')),
    'rows', jsonb_build_array(
      jsonb_build_object('what', 'Revenue from operations (turnover)', 'amount', round(rev, 2), 'pct', null),
      jsonb_build_object('what', 'Other income', 'amount', round(oth, 2), 'pct', null),
      jsonb_build_object('what', 'All receipts', 'amount', round(rin, 2), 'pct', null),
      jsonb_build_object('what', 'Receipts in cash', 'amount', round(cin, 2), 'pct', case when rin = 0 then 0 else round(100 * cin / rin, 2) end),
      jsonb_build_object('what', 'All payments', 'amount', round(pout, 2), 'pct', null),
      jsonb_build_object('what', 'Payments in cash', 'amount', round(cout, 2), 'pct', case when pout = 0 then 0 else round(100 * cout / pout, 2) end)),
    'summary', jsonb_build_object('turnover', round(rev, 2), 'cashReceiptsPct', case when rin = 0 then 0 else round(100 * cin / rin, 2) end, 'cashPaymentsPct', case when pout = 0 then 0 else round(100 * cout / pout, 2) end));
end $$;

-- (31) the AI fallback's slice of the Day Book: the entries of the dates asked (narrowed by a ledger, a party or words),
-- each with its lines, capped at p_max entries. What Claude reads when no fixed question fits; its answer is marked
-- "AI answer, not checked against the books" and every voucher it cites is checked against this slice.
create or replace function public.asst_daybook_slice(p_client text, p_from date, p_to date, p_ledger text, p_party text, p_text text, p_max integer default 300)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; l text; mx integer := least(greatest(coalesce(p_max, 300), 1), 600);
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('daybook_slice'); end if;
  if coalesce(p_ledger, '') <> '' then l := asst_match_ledger(s.bk, p_ledger); end if;
  with v as (select v.* from tally_vouchers v where v.book_id = s.bk and v.day between s.d_from and s.d_to and not v.cancelled and not v.optional and v.deleted_at is null
               and (l is null or exists (select 1 from tally_lines x where x.book_id = s.bk and x.guid = v.guid and x.ledger = l))
               and (coalesce(p_party, '') = '' or lower(v.party) like '%' || lower(p_party) || '%' or exists (select 1 from tally_lines x where x.book_id = s.bk and x.guid = v.guid and lower(x.ledger) like '%' || lower(p_party) || '%'))
               and (coalesce(p_text, '') = '' or lower(v.narration) like '%' || lower(p_text) || '%')),
  n as (select count(*) c from v),
  pick as (select * from v order by v.day, v.vno, v.guid limit mx)
  select jsonb_build_object('tool', 'daybook_slice', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to), 'ledger', l, 'count', (select c from n), 'shown', count(*),
    'entries', coalesce(jsonb_agg(jsonb_build_object('guid', p.guid, 'date', p.day, 'type', p.vtype, 'no', p.vno, 'party', p.party, 'narration', left(p.narration, 200),
        'lines', (select jsonb_agg(jsonb_build_array(x.ledger, x.amount) order by x.amount) from tally_lines x where x.book_id = s.bk and x.guid = p.guid)) order by p.day, p.vno, p.guid), '[]'::jsonb))
    into res from pick p;
  return res;
end $$;

-- (31) the purchase register: each purchase or expense bill of the period (not payments), by party: the bill number, the
-- supplier's GSTIN, the value before tax, the input tax and the bill's total. For a notice's party-wise purchase register.
create or replace function public.asst_purchase_register(p_client text, p_from date, p_to date, p_party text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('purchase_register'); end if;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  d as (select e.guid, min(e.day) as day, min(e.vno) vno, min(e.vtype) vtype, min(e.party) party, min(e.ref) ref, min(e.gstin) gstin,
          -sum(case when led.expense or led.purchase or led.fixed then e.amount else 0 end) taxable,
          -sum(case when led.kind = 'gst' and led.side = 'input' then e.amount else 0 end) tax,
          sum(case when led.creditor then e.amount else 0 end) total
          from e left join led on led.name = e.ledger group by e.guid
         having sum(case when led.expense or led.purchase or led.fixed then e.amount else 0 end) < 0
            and not bool_or(coalesce(led.bank or led.cash, false))),
  f as (select * from d where coalesce(p_party, '') = '' or lower(d.party) like '%' || lower(p_party) || '%')
  select jsonb_build_object('tool', 'purchase_register', 'title', 'Purchase register' || coalesce(' of ' || nullif(p_party, ''), ''), 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'bills (entries with a purchase, expense or fixed-asset line and no cash or bank line); value before tax from those lines; input tax from the input GST ledgers; total credited to the supplier',
    'columns', jsonb_build_array(asst_col('day', 'Date', 'date'), asst_col('vno', 'No.'), asst_col('ref', 'Bill no.'), asst_col('party', 'Supplier'), asst_col('gstin', 'GSTIN'),
      asst_col('taxable', 'Value', 'amount'), asst_col('tax', 'Input tax', 'amount'), asst_col('total', 'Bill total', 'amount')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', f.guid, 'day', f.day, 'vno', f.vno, 'ref', f.ref, 'party', f.party, 'gstin', f.gstin, 'taxable', round(f.taxable, 2), 'tax', round(f.tax, 2), 'total', round(f.total, 2)) order by f.party, f.day, f.vno), '[]'::jsonb),
    'summary', jsonb_build_object('count', count(*), 'taxable', round(coalesce(sum(f.taxable), 0), 2), 'tax', round(coalesce(sum(f.tax), 0), 2), 'total', round(coalesce(sum(f.total), 0), 2), 'parties', count(distinct f.party)))
    into res from f;
  return res;
end $$;

-- (32) payments through the bank, with the reference in the narration (UTR, NEFT, RTGS, IMPS, cheque): a list of payment
-- proofs for a notice (the bank statement itself is the user's to attach)
create or replace function public.asst_payments_list(p_client text, p_from date, p_to date, p_party text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('payments_list'); end if;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  p as (select e.guid, min(e.day) as day, min(e.vno) vno, min(e.party) party, min(e.narration) narr,
          sum(case when led.bank and e.amount > 0 then e.amount else 0 end) amt, string_agg(distinct case when led.bank and e.amount > 0 then e.ledger end, ', ') bank,
          string_agg(distinct case when e.amount < 0 and not coalesce(led.bank, false) then e.ledger end, ', ') paid_to
          from e left join led on led.name = e.ledger group by e.guid having sum(case when led.bank and e.amount > 0 then e.amount else 0 end) > 0),
  f as (select p.*, coalesce((regexp_match(upper(p.narr), '(?:UTR|NEFT|RTGS|IMPS|REF|TXN|CHQ|CHEQUE)[^A-Z0-9]{0,6}(?:NO\.?\s*)?([A-Z0-9]{6,22})'))[1], '') ref
          from p where coalesce(p_party, '') = '' or lower(p.party) like '%' || lower(p_party) || '%' or lower(coalesce(p.paid_to, '')) like '%' || lower(p_party) || '%')
  select jsonb_build_object('tool', 'payments_list', 'title', 'Payments through the bank' || coalesce(' to ' || nullif(p_party, ''), ''), 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'each entry with a credit to a bank ledger; the reference is read from the narration where one is written (UTR, NEFT, RTGS, IMPS, cheque)',
    'columns', jsonb_build_array(asst_col('day', 'Date', 'date'), asst_col('vno', 'No.'), asst_col('party', 'Paid to'), asst_col('bank', 'Bank'), asst_col('ref', 'UTR or cheque'), asst_col('amount', 'Amount', 'amount')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', f.guid, 'day', f.day, 'vno', f.vno, 'party', coalesce(nullif(f.party, ''), f.paid_to, ''), 'bank', f.bank, 'ref', f.ref, 'amount', round(f.amt, 2)) order by f.day, f.vno), '[]'::jsonb),
    'summary', jsonb_build_object('count', count(*), 'total', round(coalesce(sum(f.amt), 0), 2), 'withRef', count(*) filter (where f.ref <> '')))
    into res from f;
  return res;
end $$;

-- (33) the client's tax credit: Form 26AS (or AIS) brought into FinCom (the TDS page's 26AS and AIS: client_book_items
-- "tds26as") against the TDS receivable in the books (debits to the TDS receivable ledgers), deductor by deductor, for a
-- financial year. A deductor is the books' party the user linked to its TAN ("tanParty"), else the party of the same name.
create or replace function public.asst_tds_vs_26as(p_client text, p_fy text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; fy text := coalesce(nullif(p_fy, ''), ''); y integer; f_from date; f_to date; pan text; file jsonb;
begin
  if fy !~ '^\d{4}-\d{2}$' then
    select * into s from asst_span(p_client, null, null);
    if s.bk is null then return asst_none('tds_vs_26as'); end if;
    y := extract(year from s.d_to)::int - case when extract(month from s.d_to) < 4 then 1 else 0 end; fy := y || '-' || lpad(((y + 1) % 100)::text, 2, '0');
  end if;
  y := substr(fy, 1, 4)::int; f_from := make_date(y, 4, 1); f_to := make_date(y + 1, 3, 31);
  select * into s from asst_span(p_client, f_from, f_to);
  if s.bk is null then return asst_none('tds_vs_26as'); end if;
  select upper(coalesce(nullif(c.pan, ''), substr(c.gstin, 3, 10), '')) into pan from clients c where c.id = p_client;
  select i.data into file from client_book_items i where i.client_id = p_client and i.key = 'tds26as' and i.item like '#%' and not i.deleted
     and i.data->>'fy' = fy and (coalesce(i.data->>'pan', '') = '' or pan = '' or upper(i.data->>'pan') = pan)
   order by (i.data->>'kind' = '26AS') desc, i.updated_at desc limit 1;
  with led as (select * from asst_led(p_client, s.bk)),
  rl as (select name from led where kind in ('tds_receivable', 'tcs_receivable') or what in ('tds_receivable', 'tcs_receivable')),
  e as (select * from asst_entries(s.bk, f_from, f_to)),
  bk as (select e.guid, e.day, e.vno, -e.amount tax,
           coalesce(nullif((select v.party from tally_vouchers v where v.book_id = s.bk and v.guid = e.guid and v.party not in (select name from rl)), ''),
                    (select o.ledger from e o join led ol on ol.name = o.ledger where o.guid = e.guid and o.amount > 0 and ol.kind = '' and not ol.bank and not ol.cash order by o.amount desc limit 1), '') party
           from e where e.ledger in (select name from rl) and e.amount < 0
            and not exists (select 1 from e o where o.guid = e.guid and o.ledger in (select name from rl) and o.amount > 0)),
  fl as (select upper(coalesce(r->>'tan', '')) tan, min(coalesce(r->>'name', '')) dname, sum(coalesce((r->>'tax')::numeric, 0)) tax, count(*) n
           from jsonb_array_elements(coalesce(file->'rows', '[]'::jsonb)) r where coalesce(r->>'fy', fy) = fy and coalesce(r->>'part', 'TDS') <> 'TCS' group by 1),
  link as (select fl.*, coalesce((select i.data #>> '{}' from client_book_items i where i.client_id = p_client and i.key = 'tanParty' and i.item = '.' || fl.tan and not i.deleted limit 1),
                                 (select b.party from bk b where lower(tally_nm(b.party)) = lower(tally_nm(fl.dname)) or lower(fl.dname) like lower(b.party) || '%' or lower(b.party) like lower(fl.dname) || '%' limit 1), '') party from fl),
  rows as (select l.tan, l.dname, l.party, round(l.tax, 2) f, round(coalesce((select sum(b.tax) from bk b where l.party <> '' and b.party = l.party), 0), 2) b from link l
           union all
           select '', '', b.party, 0, round(sum(b.tax), 2) from bk b where b.party not in (select party from link where party <> '') group by b.party)
  select jsonb_build_object('tool', 'tds_vs_26as', 'title', 'Tax credit: Form ' || coalesce(file->>'kind', '26AS') || ' against the books, ' || fy, 'period', jsonb_build_object('from', f_from, 'to', f_to), 'fy', fy,
    'file', case when file is null then null else jsonb_build_object('kind', file->>'kind', 'pan', file->>'pan', 'name', file->>'file', 'at', file->>'at') end,
    'basis', 'the statement brought into FinCom on the TDS page (26AS and AIS) against the debits to the TDS receivable ledgers; a deductor is matched to the books'' party linked to its TAN, else by name',
    'columns', jsonb_build_array(asst_col('tan', 'TAN'), asst_col('deductor', 'Deductor (26AS)'), asst_col('party', 'Party in the books'), asst_col('in26as', 'TDS in 26AS', 'amount'), asst_col('books', 'TDS in the books', 'amount'), asst_col('diff', '26AS less books', 'amount'), asst_col('note', 'Note')),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('tan', r.tan, 'deductor', r.dname, 'party', r.party, 'in26as', r.f, 'books', r.b, 'diff', round(r.f - r.b, 2),
        'note', case when r.tan = '' then 'in the books only (not in 26AS)' when r.party = '' then 'in 26AS only (no party in the books)' when abs(r.f - r.b) < 1 then 'agrees' else 'differs' end) order by abs(r.f - r.b) desc, r.tan) from rows r), '[]'::jsonb),
    'summary', jsonb_build_object('in26as', coalesce((select round(sum(f), 2) from rows), 0), 'books', coalesce((select round(sum(b), 2) from rows), 0), 'diff', coalesce((select round(sum(f) - sum(b), 2) from rows), 0),
       'hasFile', file is not null, 'deductors', (select count(*) from fl)))
    into res;
  if file is null then res := res || jsonb_build_object('why', 'No Form 26AS or AIS for ' || fy || ' has been brought into FinCom (TDS page › 26AS and AIS).'); end if;
  return res;
end $$;

-- the GSTR-3B the firm fetched from the portal for a month (gst_returns '3B', period MMYYYY): input tax by table 4(A) and
-- outward taxable value of 3.1(a)
create or replace function public.asst_3b_filed(p_regs text[], p_ym text)
returns jsonb language sql stable security invoker set search_path = public, pg_temp as $$
  select jsonb_build_object('have', count(*) > 0,
    'itc_oth', coalesce(sum((select sum(coalesce((x->>'iamt')::numeric, 0) + coalesce((x->>'camt')::numeric, 0) + coalesce((x->>'samt')::numeric, 0) + coalesce((x->>'csamt')::numeric, 0))
                   from jsonb_path_query(g.data, 'strict $.**.itc_avl[*]') x where x->>'ty' = 'OTH')), 0),
    'itc_rcm', coalesce(sum((select sum(coalesce((x->>'iamt')::numeric, 0) + coalesce((x->>'camt')::numeric, 0) + coalesce((x->>'samt')::numeric, 0) + coalesce((x->>'csamt')::numeric, 0))
                   from jsonb_path_query(g.data, 'strict $.**.itc_avl[*]') x where x->>'ty' in ('ISRC', 'IMPS'))), 0),
    'itc_all', coalesce(sum((select sum(coalesce((x->>'iamt')::numeric, 0) + coalesce((x->>'camt')::numeric, 0) + coalesce((x->>'samt')::numeric, 0) + coalesce((x->>'csamt')::numeric, 0))
                   from jsonb_path_query(g.data, 'strict $.**.itc_avl[*]') x)), 0),
    'taxable', coalesce(sum((select sum(coalesce((x->>'txval')::numeric, 0)) from jsonb_path_query(g.data, 'strict $.**.osup_det') x)), 0))
  from gst_returns g where g.form = '3B' and g.status = 'ok' and upper(g.gstin) = any(coalesce(p_regs, '{}')) and g.period = substr(p_ym, 5, 2) || substr(p_ym, 1, 4)
$$;

-- (34) input tax, three ways, month by month: the books (registered suppliers' invoices, and reverse charge), GSTR-2B, and
-- GSTR-3B as filed (fetched from the portal): for an ASMT-10 or DRC-01 on ITC
create or replace function public.asst_itc_3way(p_client text, p_from date, p_to date, p_gstin text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; i2b jsonb; rc jsonb; regs text[];
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('itc_3way'); end if;
  i2b := asst_itc_vs_2b(p_client, s.d_from, s.d_to, p_gstin); rc := asst_rcm(p_client, s.d_from, s.d_to);
  select array_agg(distinct upper(g)) into regs from (select v.cmp_gstin g from tally_vouchers v where v.book_id = s.bk and coalesce(v.cmp_gstin, '') <> ''
                                                       union select c.gstin from clients c where c.id = p_client and coalesce(c.gstin, '') <> '') z
   where coalesce(p_gstin, '') = '' or upper(g) = upper(p_gstin);
  with m as (select to_char(d, 'YYYYMM') ym from generate_series(date_trunc('month', s.d_from), s.d_to, interval '1 month') d),
  x as (select m.ym, coalesce((i2b->'summary'->'byMonth'->m.ym->>'books')::numeric, 0) books, coalesce((i2b->'summary'->'byMonth'->m.ym->>'twob')::numeric, 0) twob,
          coalesce((select sum((r->>'tax')::numeric) from jsonb_array_elements(rc->'rows') r where to_char((r->>'day')::date, 'YYYYMM') = m.ym), 0) rcm,
          i2b->'months2b' ? m.ym has2b, asst_3b_filed(regs, m.ym) b3 from m)
  select jsonb_build_object('tool', 'itc_3way', 'title', 'Input tax: books, GSTR-2B and GSTR-3B', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'books: input GST on registered suppliers'' invoices (not reverse charge) and reverse-charge tax on the documents; 2B: the 2Bs brought into FinCom; 3B: the returns fetched from the portal, table 4(A)(5) all other ITC and 4(A)(3) inward supplies liable to reverse charge',
    'columns', jsonb_build_array(asst_col('month', 'Month'), asst_col('books', 'Books: invoices', 'amount'), asst_col('twob', 'GSTR-2B', 'amount'), asst_col('b3oth', '3B 4(A)(5)', 'amount'),
      asst_col('rcm', 'Books: reverse charge', 'amount'), asst_col('b3rcm', '3B 4(A)(3)', 'amount'), asst_col('b3all', '3B: all ITC', 'amount'), asst_col('excess', '3B less 2B', 'amount'), asst_col('note', 'Note')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('month', to_char(to_date(x.ym, 'YYYYMM'), 'Mon-YYYY'), 'ym', x.ym, 'books', round(x.books, 2), 'twob', case when x.has2b then round(x.twob, 2) end,
        'b3oth', case when (x.b3->>'have')::boolean then round((x.b3->>'itc_oth')::numeric, 2) end, 'rcm', round(x.rcm, 2), 'b3rcm', case when (x.b3->>'have')::boolean then round((x.b3->>'itc_rcm')::numeric, 2) end,
        'b3all', case when (x.b3->>'have')::boolean then round((x.b3->>'itc_all')::numeric, 2) end,
        'excess', case when (x.b3->>'have')::boolean and x.has2b then round((x.b3->>'itc_all')::numeric - x.twob, 2) end,
        'note', case when not (x.b3->>'have')::boolean then 'no GSTR-3B fetched for the month' when not x.has2b then 'no 2B for the month in FinCom'
                     when abs((x.b3->>'itc_all')::numeric - x.twob) < 1 then 'agrees'
                     when abs((x.b3->>'itc_all')::numeric - x.twob - (x.b3->>'itc_rcm')::numeric) < 1 then '3B is more than 2B by the reverse-charge credit only (not shown in 2B)'
                     else 'differs' end) order by x.ym), '[]'::jsonb),
    'summary', jsonb_build_object('books', round(sum(x.books), 2), 'twob', round(sum(x.twob), 2), 'rcm', round(sum(x.rcm), 2),
       'b3all', round(sum(coalesce((x.b3->>'itc_all')::numeric, 0)), 2), 'b3rcm', round(sum(coalesce((x.b3->>'itc_rcm')::numeric, 0)), 2), 'b3oth', round(sum(coalesce((x.b3->>'itc_oth')::numeric, 0)), 2),
       'excess', round(sum(case when (x.b3->>'have')::boolean and x.has2b then (x.b3->>'itc_all')::numeric - x.twob else 0 end), 2),
       'monthsWith3b', count(*) filter (where (x.b3->>'have')::boolean)))
    into res from x;
  return res;
end $$;

-- (35) turnover, three ways, month by month: the books, GSTR-1 as filed and GSTR-3B 3.1(a) as filed
create or replace function public.asst_turnover_3way(p_client text, p_from date, p_to date, p_gstin text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; r1 jsonb; regs text[];
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('turnover_3way'); end if;
  r1 := asst_sales_vs_r1(p_client, s.d_from, s.d_to, p_gstin);
  select array_agg(distinct upper(g)) into regs from (select v.cmp_gstin g from tally_vouchers v where v.book_id = s.bk and coalesce(v.cmp_gstin, '') <> ''
                                                       union select c.gstin from clients c where c.id = p_client and coalesce(c.gstin, '') <> '') z
   where coalesce(p_gstin, '') = '' or upper(g) = upper(p_gstin);
  with m as (select to_char(d, 'YYYYMM') ym from generate_series(date_trunc('month', s.d_from), s.d_to, interval '1 month') d),
  x as (select m.ym, coalesce((select sum((r->>'books')::numeric) from jsonb_array_elements(r1->'rows') r where r->>'month' = to_char(to_date(m.ym, 'YYYYMM'), 'Mon-YYYY')), 0) books,
          (select sum((r->>'r1')::numeric) from jsonb_array_elements(r1->'rows') r where r->>'month' = to_char(to_date(m.ym, 'YYYYMM'), 'Mon-YYYY') and r->>'r1' is not null) gstr1,
          asst_3b_filed(regs, m.ym) b3 from m)
  select jsonb_build_object('tool', 'turnover_3way', 'title', 'Turnover: books, GSTR-1 and GSTR-3B', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'books: taxable value of sales entries; GSTR-1 and GSTR-3B 3.1(a): the returns fetched from the portal into FinCom',
    'columns', jsonb_build_array(asst_col('month', 'Month'), asst_col('books', 'Books', 'amount'), asst_col('gstr1', 'GSTR-1', 'amount'), asst_col('gstr3b', 'GSTR-3B 3.1(a)', 'amount'), asst_col('note', 'Note')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('month', to_char(to_date(x.ym, 'YYYYMM'), 'Mon-YYYY'), 'books', round(x.books, 2), 'gstr1', round(x.gstr1, 2),
        'gstr3b', case when (x.b3->>'have')::boolean then round((x.b3->>'taxable')::numeric, 2) end,
        'note', case when x.gstr1 is null and not (x.b3->>'have')::boolean then 'no return fetched for the month'
                     when abs(x.books - coalesce(x.gstr1, x.books)) < 1 and abs(x.books - case when (x.b3->>'have')::boolean then (x.b3->>'taxable')::numeric else x.books end) < 1 then 'agrees' else 'differs' end) order by x.ym), '[]'::jsonb),
    'summary', jsonb_build_object('books', round(sum(x.books), 2), 'gstr1', round(sum(coalesce(x.gstr1, 0)), 2), 'gstr3b', round(sum(case when (x.b3->>'have')::boolean then (x.b3->>'taxable')::numeric else 0 end), 2)))
    into res from x;
  return res;
end $$;

-- the clients the user's firm has (for a firm-wide question): name, GSTIN, whether books are held
