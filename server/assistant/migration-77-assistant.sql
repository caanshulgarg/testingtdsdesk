-- before a Claude call: may the firm make one? (under its rupee cap and its call limit). Takes the call when it may.
create or replace function public.asst_cap_take(p_firm uuid, p_n integer default 1)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare c record; d date := (now() at time zone 'Asia/Kolkata')::date; used integer; spent numeric;
begin
  if p_firm is null or coalesce(p_n, 0) < 1 then return jsonb_build_object('ok', false, 'used', 0, 'cap', 0); end if;
  select coalesce(x.daily_calls, 500) calls, coalesce(x.daily_inr, 150) inr, coalesce(x.inr_per_usd, 85) rate into c
    from (select 1) z left join assistant_caps x on x.firm_id = p_firm;
  insert into assistant_usage (firm_id, day) values (p_firm, d) on conflict (firm_id, day) do nothing;
  update assistant_usage u set calls = u.calls + p_n where u.firm_id = p_firm and u.day = d and u.calls + p_n <= c.calls and u.cost_inr < c.inr
  returning u.calls, u.cost_inr into used, spent;
  if used is null then
    select u.calls, u.cost_inr into used, spent from assistant_usage u where u.firm_id = p_firm and u.day = d;
    return jsonb_build_object('ok', false, 'used', coalesce(used, 0), 'cap', c.calls, 'spent_inr', round(coalesce(spent, 0), 2), 'cap_inr', c.inr, 'rate', c.rate, 'day', d,
      'why', case when coalesce(spent, 0) >= c.inr then 'inr' else 'calls' end);
  end if;
  return jsonb_build_object('ok', true, 'used', used, 'cap', c.calls, 'spent_inr', round(spent, 2), 'cap_inr', c.inr, 'rate', c.rate, 'day', d, 'warn', spent >= 0.8 * c.inr);
end $$;

-- after a Claude call: its cost (in dollars, from the API's usage and the model's price) in rupees at the firm's rate,
-- added to the day and the feature. Returns what the firm has spent today against its cap.
create or replace function public.asst_cost_add(p_firm uuid, p_feature text, p_cost_usd numeric, p_in integer, p_out integer, p_cache_read integer, p_cache_write integer)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare d date := (now() at time zone 'Asia/Kolkata')::date; rate numeric; cap numeric; inr numeric; spent numeric;
begin
  select coalesce(x.inr_per_usd, 85), coalesce(x.daily_inr, 150) into rate, cap from (select 1) z left join assistant_caps x on x.firm_id = p_firm;
  inr := round(greatest(coalesce(p_cost_usd, 0), 0) * rate, 4);
  insert into assistant_usage (firm_id, day) values (p_firm, d) on conflict (firm_id, day) do nothing;
  update assistant_usage u set input_tokens = u.input_tokens + greatest(coalesce(p_in, 0), 0), output_tokens = u.output_tokens + greatest(coalesce(p_out, 0), 0),
         cache_read = u.cache_read + greatest(coalesce(p_cache_read, 0), 0), cache_write = u.cache_write + greatest(coalesce(p_cache_write, 0), 0), cost_inr = u.cost_inr + inr
   where u.firm_id = p_firm and u.day = d returning u.cost_inr into spent;
  insert into assistant_usage_feature (firm_id, day, feature, calls, cost_inr) values (p_firm, d, left(coalesce(nullif(p_feature, ''), 'other'), 40), 1, inr)
  on conflict (firm_id, day, feature) do update set calls = assistant_usage_feature.calls + 1, cost_inr = assistant_usage_feature.cost_inr + excluded.cost_inr;
  return jsonb_build_object('inr', inr, 'spent_inr', round(spent, 2), 'cap_inr', cap, 'warn', spent >= 0.8 * cap, 'over', spent >= cap);
end $$;

create or replace function public.asst_log_add(p_firm uuid, p_user uuid, p_client text, p_question text, p_tools text[],
  p_in integer, p_out integer, p_calls integer, p_ms integer, p_feature text default '', p_route text default '', p_models text[] default '{}',
  p_cache_read integer default 0, p_cache_write integer default 0, p_cost_inr numeric default 0, p_fell_through boolean default false)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare d date := (now() at time zone 'Asia/Kolkata')::date;
begin
  insert into assistant_log (firm_id, user_id, client_id, question, tools, input_tokens, output_tokens, calls, ms, feature, route, models, cache_read, cache_write, cost_inr, fell_through)
  values (p_firm, p_user, left(coalesce(p_client, ''), 120), left(coalesce(p_question, ''), 2000),
          coalesce((select array_agg(left(t, 60)) from unnest(coalesce(p_tools, '{}')) t), '{}'),
          greatest(coalesce(p_in, 0), 0), greatest(coalesce(p_out, 0), 0), greatest(coalesce(p_calls, 0), 0), greatest(coalesce(p_ms, 0), 0),
          left(coalesce(p_feature, ''), 40), left(coalesce(p_route, ''), 20), coalesce((select array_agg(left(t, 40)) from unnest(coalesce(p_models, '{}')) t), '{}'),
          greatest(coalesce(p_cache_read, 0), 0), greatest(coalesce(p_cache_write, 0), 0), greatest(coalesce(p_cost_inr, 0), 0), coalesce(p_fell_through, false));
  insert into assistant_usage_feature (firm_id, day, feature, questions) values (p_firm, d, left(coalesce(nullif(p_feature, ''), 'other'), 40), 1)
  on conflict (firm_id, day, feature) do update set questions = assistant_usage_feature.questions + 1;
end $$;

-- what the caller may see of the firm's use: everyone today's spend and the cap (and the 80% warning); the owner also the
-- days, the months, the features that use the money, the questions, and the questions no fixed question fitted
create or replace function public.asst_usage(p_days integer default 30)
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare f uuid := my_firm(); owner boolean; d date := (now() at time zone 'Asia/Kolkata')::date; c record; spent numeric; n integer; since date;
begin
  if f is null then return jsonb_build_object('none', true); end if;
  owner := exists (select 1 from members m where m.user_id = auth.uid() and m.firm_id = f and m.active and m.role = 'owner');
  select coalesce(x.daily_calls, 500) calls, coalesce(x.daily_inr, 150) inr, coalesce(x.inr_per_usd, 85) rate into c from (select 1) z left join assistant_caps x on x.firm_id = f;
  select coalesce(u.cost_inr, 0), coalesce(u.calls, 0) into spent, n from (select 1) z left join assistant_usage u on u.firm_id = f and u.day = d;
  since := d - least(greatest(coalesce(p_days, 30), 1), 366);
  return jsonb_build_object('cap', c.calls, 'today', n, 'owner', owner, 'cap_inr', c.inr, 'rate', c.rate, 'spent_inr', round(spent, 2),
    'warn', spent >= 0.8 * c.inr, 'over', spent >= c.inr,
    'days', case when owner then coalesce((select jsonb_agg(jsonb_build_object('day', u.day, 'calls', u.calls, 'in', u.input_tokens, 'out', u.output_tokens, 'cache_read', u.cache_read, 'inr', round(u.cost_inr, 2)) order by u.day desc)
              from assistant_usage u where u.firm_id = f and u.day > since), '[]'::jsonb) else null end,
    'months', case when owner then coalesce((select jsonb_agg(jsonb_build_object('month', z.m, 'calls', z.calls, 'inr', z.inr) order by z.m desc) from
              (select to_char(u.day, 'YYYY-MM') m, sum(u.calls) calls, round(sum(u.cost_inr), 2) inr from assistant_usage u where u.firm_id = f and u.day > d - 366 group by 1) z), '[]'::jsonb) else null end,
    'features', case when owner then coalesce((select jsonb_agg(jsonb_build_object('feature', z.feature, 'questions', z.q, 'calls', z.calls, 'inr', z.inr) order by z.inr desc, z.feature) from
              (select x.feature, sum(x.questions) q, sum(x.calls) calls, round(sum(x.cost_inr), 2) inr from assistant_usage_feature x where x.firm_id = f and x.day > since group by 1) z), '[]'::jsonb) else null end,
    'questions', case when owner then coalesce((select jsonb_agg(jsonb_build_object('at', l.at, 'q', l.question, 'tools', l.tools, 'client', l.client_id, 'in', l.input_tokens, 'out', l.output_tokens,
              'route', l.route, 'feature', l.feature, 'inr', round(l.cost_inr, 2), 'fell', l.fell_through,
              'by', coalesce((select m.name from members m where m.user_id = l.user_id and m.firm_id = f limit 1), '')) order by l.at desc)
              from (select * from assistant_log x where x.firm_id = f order by x.at desc limit 200) l), '[]'::jsonb) else null end,
    'fell_through', case when owner then coalesce((select jsonb_agg(jsonb_build_object('q', z.q, 'n', z.n) order by z.n desc, z.q) from
              (select l.question q, count(*) n from assistant_log l where l.firm_id = f and l.fell_through and l.at > now() - interval '90 days' group by 1 order by 2 desc limit 50) z), '[]'::jsonb) else null end);
end $$;

-- the owner sets the firm's daily cap in rupees and the rate (null keeps it)
create or replace function public.asst_set_cap(p_inr numeric, p_rate numeric default null)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare f uuid := my_firm();
begin
  if f is null or not exists (select 1 from members m where m.user_id = auth.uid() and m.firm_id = f and m.active and m.role = 'owner') then
    raise exception 'only the firm''s owner sets the cap';
  end if;
  if (p_inr is not null and (p_inr < 0 or p_inr > 1000000)) or (p_rate is not null and (p_rate < 1 or p_rate > 1000)) then raise exception 'cap out of range'; end if;
  insert into assistant_caps (firm_id, daily_inr, inr_per_usd, set_at, set_by) values (f, coalesce(p_inr, 150), coalesce(p_rate, 85), now(), auth.uid())
  on conflict (firm_id) do update set daily_inr = coalesce(p_inr, assistant_caps.daily_inr), inr_per_usd = coalesce(p_rate, assistant_caps.inr_per_usd), set_at = now(), set_by = auth.uid();
  return jsonb_build_object('ok', true, 'cap_inr', (select daily_inr from assistant_caps where firm_id = f), 'rate', (select inr_per_usd from assistant_caps where firm_id = f));
end $$;

