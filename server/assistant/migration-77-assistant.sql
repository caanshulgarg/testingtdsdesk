  insert into assistant_notice_events (notice_id, firm_id, by_user, what) values (n.id, n.firm_id, auth.uid(), 'status: ' || p_status || coalesce(' (' || nullif(btrim(p_ack), '') || ')', ''));
  return to_jsonb(n);
end $$;

