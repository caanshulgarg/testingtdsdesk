    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', v.guid, 'day', v.day, 'dow', case when to_char(v.day, 'MMDD') in ('0126', '0815', '1002') then 'holiday' else trim(to_char(v.day, 'Day')) end, 'vtype', v.vtype, 'vno', v.vno, 'party', v.party, 'amount', round(v.amt, 2)) order by v.day, v.vno), '[]'::jsonb),
    'summary', jsonb_build_object('count', count(*)))
    into res from v;
  return res;
end $$;

-- (28) payroll: salary and staff costs by month (the employee-cost ledgers, as MIS heads them), and the salary paid to
-- each employee where Tally's payroll gives it (tally_salary_pays)
create or replace function public.asst_payroll(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
