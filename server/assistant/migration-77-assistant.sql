    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', r.guid, 'day', r.day, 'vno', r.vno, 'party', r.party, 'narration', left(r.narr, 120), 'amount', round(r.amt, 2), 'kind', r.kind) order by r.day, r.vno), '[]'::jsonb),
    'summary', jsonb_build_object('count', count(*), 'amount', round(coalesce(sum(r.amt), 0), 2)))
    into res from r;
  return res;
end $$;

-- (27) sales, purchases, receipts and payments dated on a Sunday or a national holiday (26 Jan, 15 Aug, 2 Oct); Saturdays
-- too when asked
create or replace function public.asst_weekend(p_client text, p_from date, p_to date, p_saturday boolean default false)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('weekend'); end if;
  with v as (select v.guid, v.day, v.vno, v.vtype, v.party, (select max(abs(l.amount)) from tally_lines l where l.book_id = s.bk and l.guid = v.guid) amt from tally_vouchers v
              where v.book_id = s.bk and v.day between s.d_from and s.d_to and not v.cancelled and not v.optional and v.deleted_at is null
                and v.vtype ~* 'sales|purchase|receipt|payment'
                and (extract(dow from v.day) = 0 or (coalesce(p_saturday, false) and extract(dow from v.day) = 6) or to_char(v.day, 'MMDD') in ('0126', '0815', '1002')))
  select jsonb_build_object('tool', 'weekend', 'title', 'Entries dated on a Sunday' || case when p_saturday then ' or Saturday' else '' end || ' or a national holiday', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
