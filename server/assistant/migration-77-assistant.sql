  -- reverse charge of each month: the tax on the documents (asst_rcm), not its payment
  select coalesce(jsonb_object_agg(z.ym, z.t), '{}'::jsonb) into rm from (select to_char((r->>'day')::date, 'YYYYMM') ym, sum((r->>'tax')::numeric) t from jsonb_array_elements(asst_rcm(p_client, s.d_from, s.d_to)->'rows') r group by 1) z;
  if coalesce((g->>'none')::boolean, false) then return asst_none('gst_summary'); end if;
  return jsonb_build_object('tool', 'gst_summary', 'title', 'GST month by month (all registrations together)', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'tax on documents only (sales, purchases, expenses), from the GST ledgers as confirmed in FinCom; not the set-off or payments; input tax includes the credit of reverse-charge tax',
