-- (2) ledgers by name or group, with the balance on a date
create or replace function public.asst_find_ledgers(p_client text, p_text text, p_group text, p_as_on date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; ws text[] := array_remove(regexp_split_to_array(lower(btrim(coalesce(p_text, ''))), '\s+'), '');
begin
  select * into s from asst_span(p_client, null, p_as_on);
  if s.bk is null then return asst_none('find_ledgers'); end if;
  with led as (select * from asst_led(p_client, s.bk) l
                where (coalesce(p_text, '') = '' or not exists (select 1 from unnest(ws) x where position(x in lower(l.name)) = 0))
                  and (coalesce(p_group, '') = '' or exists (select 1 from unnest(l.chain || array[l.parent]) g where lower(g) like '%' || lower(p_group) || '%'))),
  mv as (select d.ledger, sum(d.amount) a from tally_ledger_day d join led on led.name = d.ledger where d.book_id = s.bk and d.day <= s.d_to group by d.ledger),
  r as (select led.name, led.parent, round(led.open + coalesce(mv.a, 0), 2) as c from led left join mv on mv.ledger = led.name order by led.name limit 200)
  select jsonb_build_object('tool', 'find_ledgers', 'title', 'Ledgers' || coalesce(' matching "' || nullif(p_text, '') || '"', '') || coalesce(' under ' || nullif(p_group, ''), ''), 'asOn', s.d_to,
    'columns', jsonb_build_array(asst_col('ledger', 'Ledger'), asst_col('group', 'Group'), asst_col('balance', 'Balance', 'amount'), asst_col('side', 'Dr/Cr')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('ledger', r.name, 'group', r.parent, 'balance', abs(r.c), 'side', case when r.c < 0 then 'Dr' when r.c > 0 then 'Cr' else '' end)), '[]'::jsonb),
    'count', count(*))
    into res from r;
  return res;
end $$;

-- (3) a ledger's balance on a date: opening of the book, movement to the date, closing
create or replace function public.asst_ledger_balance(p_client text, p_ledger text, p_as_on date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; l text; o numeric; mv numeric; dr numeric; cr numeric; c numeric; f date;
begin
  select * into s from asst_span(p_client, null, p_as_on);
  if s.bk is null then return asst_none('ledger_balance'); end if;
  l := asst_match_ledger(s.bk, p_ledger);
  if l is null then return jsonb_build_object('tool', 'ledger_balance', 'none', true, 'why', 'No ledger matches "' || coalesce(p_ledger, '') || '". Use find_ledgers to list the names.'); end if;
  select b.from_date into f from tally_books b where b.book_id = s.bk;
  select coalesce(t.open, 0) into o from tally_ledgers t where t.book_id = s.bk and t.name = l;
  select coalesce(sum(d.amount), 0), coalesce(sum(d.dr), 0), coalesce(sum(d.cr), 0) into mv, dr, cr from tally_ledger_day d where d.book_id = s.bk and d.ledger = l and d.day between f and s.d_to;
  c := coalesce(o, 0) + mv;
  return jsonb_build_object('tool', 'ledger_balance', 'title', l || ': balance on ' || to_char(s.d_to, 'DD-Mon-YYYY'), 'ledger', l, 'asOn', s.d_to,
    'columns', jsonb_build_array(asst_col('what', ''), asst_col('amount', 'Amount', 'amount'), asst_col('side', 'Dr/Cr')),
    'rows', jsonb_build_array(
      jsonb_build_object('what', 'Opening on ' || to_char(f, 'DD-Mon-YYYY'), 'amount', round(abs(coalesce(o, 0)), 2), 'side', case when o < 0 then 'Dr' when o > 0 then 'Cr' else '' end),
      jsonb_build_object('what', 'Debits to the date', 'amount', round(dr, 2), 'side', 'Dr'),
      jsonb_build_object('what', 'Credits to the date', 'amount', round(cr, 2), 'side', 'Cr'),
      jsonb_build_object('what', 'Closing', 'amount', round(abs(c), 2), 'side', case when c < 0 then 'Dr' when c > 0 then 'Cr' else '' end)),
    'summary', jsonb_build_object('closing', round(abs(c), 2), 'side', case when c < 0 then 'Dr' when c > 0 then 'Cr' else '' end));
end $$;

-- (4) a ledger month by month: debits, credits, net, running balance
create or replace function public.asst_ledger_movement(p_client text, p_ledger text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; l text; f date; ob numeric; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('ledger_movement'); end if;
  l := asst_match_ledger(s.bk, p_ledger);
  if l is null then return jsonb_build_object('tool', 'ledger_movement', 'none', true, 'why', 'No ledger matches "' || coalesce(p_ledger, '') || '".'); end if;
  select b.from_date into f from tally_books b where b.book_id = s.bk;
  select coalesce((select t.open from tally_ledgers t where t.book_id = s.bk and t.name = l), 0) + coalesce((select sum(d.amount) from tally_ledger_day d where d.book_id = s.bk and d.ledger = l and d.day >= f and d.day < s.d_from), 0) into ob;
  with mo as (select to_char(gs, 'YYYYMM') ym, gs::date m from generate_series(date_trunc('month', s.d_from), date_trunc('month', s.d_to), interval '1 month') gs),
  mm as (select to_char(d.day, 'YYYYMM') ym, sum(d.dr) dr, sum(d.cr) cr, sum(d.amount) a from tally_ledger_day d where d.book_id = s.bk and d.ledger = l and d.day between s.d_from and s.d_to group by 1),
  r as (select mo.ym, mo.m, coalesce(mm.dr, 0) dr, coalesce(mm.cr, 0) cr, coalesce(mm.a, 0) a, ob + sum(coalesce(mm.a, 0)) over (order by mo.ym) bal from mo left join mm on mm.ym = mo.ym)
  select jsonb_build_object('tool', 'ledger_movement', 'title', l || ' month by month', 'ledger', l, 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'columns', jsonb_build_array(asst_col('month', 'Month'), asst_col('debit', 'Debit', 'amount'), asst_col('credit', 'Credit', 'amount'), asst_col('balance', 'Balance', 'amount'), asst_col('side', 'Dr/Cr')),
    'rows', jsonb_agg(jsonb_build_object('month', to_char(r.m, 'Mon-YYYY'), 'debit', round(r.dr, 2), 'credit', round(r.cr, 2), 'balance', round(abs(r.bal), 2), 'side', case when r.bal < 0 then 'Dr' when r.bal > 0 then 'Cr' else '' end) order by r.ym),
    'summary', jsonb_build_object('opening', round(abs(ob), 2), 'openingSide', case when ob < 0 then 'Dr' when ob > 0 then 'Cr' else '' end, 'debit', round(sum(r.dr), 2), 'credit', round(sum(r.cr), 2)))
    into res from r;
  return res;
end $$;

-- (5) a ledger's entries in a period (the ledger account)
create or replace function public.asst_ledger_entries(p_client text, p_ledger text, p_from date, p_to date, p_limit integer default 200)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; l text; f date; ob numeric; res jsonb; n integer;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('ledger_entries'); end if;
  l := asst_match_ledger(s.bk, p_ledger);
  if l is null then return jsonb_build_object('tool', 'ledger_entries', 'none', true, 'why', 'No ledger matches "' || coalesce(p_ledger, '') || '".'); end if;
  select b.from_date into f from tally_books b where b.book_id = s.bk;
  select coalesce((select t.open from tally_ledgers t where t.book_id = s.bk and t.name = l), 0) + coalesce((select sum(d.amount) from tally_ledger_day d where d.book_id = s.bk and d.ledger = l and d.day >= f and d.day < s.d_from), 0) into ob;
  select count(*) into n from asst_entries(s.bk, s.d_from, s.d_to) e where e.ledger = l;
  with e as (select x.*, ob + sum(x.amount) over (order by x.day, x.vno, x.guid) bal from asst_entries(s.bk, s.d_from, s.d_to) x where x.ledger = l order by x.day, x.vno, x.guid limit least(greatest(coalesce(p_limit, 200), 1), 500))
  select jsonb_build_object('tool', 'ledger_entries', 'title', l || ', ' || to_char(s.d_from, 'DD-Mon-YYYY') || ' to ' || to_char(s.d_to, 'DD-Mon-YYYY'), 'ledger', l,
    'period', jsonb_build_object('from', s.d_from, 'to', s.d_to), 'count', n, 'shown', count(*),
    'columns', jsonb_build_array(asst_col('day', 'Date', 'date'), asst_col('vtype', 'Type'), asst_col('vno', 'No.'), asst_col('party', 'Party'), asst_col('narration', 'Narration'),
      asst_col('debit', 'Debit', 'amount'), asst_col('credit', 'Credit', 'amount'), asst_col('balance', 'Balance', 'amount'), asst_col('side', 'Dr/Cr')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', e.guid, 'day', e.day, 'vtype', e.vtype, 'vno', e.vno, 'party', e.party, 'narration', left(e.narration, 120),
       'debit', case when e.amount < 0 then round(-e.amount, 2) else 0 end, 'credit', case when e.amount > 0 then round(e.amount, 2) else 0 end,
       'balance', round(abs(e.bal), 2), 'side', case when e.bal < 0 then 'Dr' when e.bal > 0 then 'Cr' else '' end) order by e.day, e.vno, e.guid), '[]'::jsonb),
    'summary', jsonb_build_object('opening', round(abs(ob), 2), 'openingSide', case when ob < 0 then 'Dr' when ob > 0 then 'Cr' else '' end))
    into res from e;
  return res;
end $$;

-- (6) top customers or suppliers: by sales (Sales Accounts lines of each entry, under its party), by purchases and
-- expenses booked to a supplier (the supplier's credits on purchase and expense entries), or by balance on the last date
create or replace function public.asst_top_parties(p_client text, p_side text, p_measure text, p_from date, p_to date, p_limit integer default 10)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; v_side text := case when lower(coalesce(p_side, '')) like 'sup%' then 'suppliers' else 'customers' end;
  v_meas text := case when lower(coalesce(p_measure, '')) like 'bal%' or lower(coalesce(p_measure, '')) like 'out%' then 'balance' else 'turnover' end;
  v_lim integer := least(greatest(coalesce(p_limit, 10), 1), 100); f date;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('top_parties'); end if;
  select b.from_date into f from tally_books b where b.book_id = s.bk;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  bal as (select l.name party, round(case when v_side = 'customers' then -(l.open + coalesce(sum(d.amount), 0)) else l.open + coalesce(sum(d.amount), 0) end, 2) amount, count(d.*)::int n
            from led l left join tally_ledger_day d on d.book_id = s.bk and d.ledger = l.name and d.day between f and s.d_to
           where v_meas = 'balance' and ((v_side = 'customers' and l.debtor) or (v_side = 'suppliers' and l.creditor)) group by l.name, l.open),
  sl as (select e.guid, sum(e.amount) a from e join led on led.name = e.ledger and led.sales where v_meas <> 'balance' and v_side = 'customers' group by e.guid),
  cus as (select coalesce(nullif((select v.party from tally_vouchers v where v.book_id = s.bk and v.guid = sl.guid), ''), '(no party)') party, round(sum(sl.a), 2) amount, count(*)::int n from sl group by 1),
  docs as (select distinct e.guid from e join led on led.name = e.ledger and (led.purchase or led.expense or led.fixed) and e.amount < 0 where v_meas <> 'balance' and v_side = 'suppliers'),
  sup as (select e.ledger party, round(sum(e.amount), 2) amount, count(distinct e.guid)::int n from e join docs on docs.guid = e.guid join led on led.name = e.ledger and led.creditor where e.amount > 0 group by e.ledger),
  t as (select * from bal where amount > 0 union all select * from cus union all select * from sup)
    select jsonb_build_object('tool', 'top_parties', 'title', 'Top ' || v_lim || ' ' || v_side || ' by ' || case when v_meas = 'balance' then 'balance on ' || to_char(s.d_to, 'DD-Mon-YYYY') when v_side = 'customers' then 'sales' else 'purchases and expenses' end,
    'period', jsonb_build_object('from', s.d_from, 'to', s.d_to), 'basis', case when v_meas = 'balance' then 'balance' when v_side = 'customers' then 'sales: Sales Accounts lines, before GST' else 'bills: the amount credited to the supplier, GST included, before TDS' end,
    'columns', jsonb_build_array(asst_col('rank', '#', 'int'), asst_col('party', case when v_side = 'customers' then 'Customer' else 'Supplier' end), asst_col('amount', case when v_meas = 'balance' then 'Balance' when v_side = 'customers' then 'Sales' else 'Billed' end, 'amount'), asst_col('n', 'Entries', 'int'), asst_col('share', 'Share %', 'pct')),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('rank', z.rk, 'party', z.party, 'amount', z.amount, 'n', z.n, 'share', case when z.tot = 0 then 0 else round(100 * z.amount / z.tot, 1) end) order by z.rk)
       from (select t2.*, row_number() over (order by t2.amount desc, t2.party) rk, sum(t2.amount) over () tot from t t2) z where z.rk <= v_lim), '[]'::jsonb),
    'summary', jsonb_build_object('total', coalesce((select round(sum(amount), 2) from t), 0), 'parties', (select count(*) from t)))
    into res;
  return res;
end $$;

-- (7) entries by filter: dates, amount, cash or bank, payment or receipt, a ledger, a party, a voucher type, words in the
-- narration. The amount of an entry is the larger of its debits and its credits.
create or replace function public.asst_entries_filter(p_client text, p_from date, p_to date, p_min numeric, p_max numeric, p_mode text, p_direction text,
  p_ledger text, p_party text, p_vtype text, p_text text, p_limit integer default 200)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; l text; mode text := lower(coalesce(p_mode, 'any')); dir text := lower(coalesce(p_direction, 'any'));
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('entries_filter'); end if;
  if coalesce(p_ledger, '') <> '' then
    l := asst_match_ledger(s.bk, p_ledger);
    if l is null then return jsonb_build_object('tool', 'entries_filter', 'none', true, 'why', 'No ledger matches "' || p_ledger || '".'); end if;
  end if;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  v as (select e.guid, min(e.day) as day, min(e.vtype) vtype, min(e.vno) vno, min(e.party) party, min(e.narration) narration,
          greatest(sum(case when e.amount < 0 then -e.amount else 0 end), sum(case when e.amount > 0 then e.amount else 0 end)) amt,
          sum(case when led.cash and e.amount > 0 then e.amount else 0 end) cash_out, sum(case when led.cash and e.amount < 0 then -e.amount else 0 end) cash_in,
          sum(case when led.bank and e.amount > 0 then e.amount else 0 end) bank_out, sum(case when led.bank and e.amount < 0 then -e.amount else 0 end) bank_in,
          bool_or(e.ledger = l) has_l, string_agg(distinct e.ledger, ', ') ledgers
          from e left join led on led.name = e.ledger group by e.guid),
  f as (select v.*, case when mode = 'cash' then case when dir like 'pay%' then v.cash_out when dir like 'rec%' then v.cash_in else greatest(v.cash_out, v.cash_in) end
                         when mode = 'bank' then case when dir like 'pay%' then v.bank_out when dir like 'rec%' then v.bank_in else greatest(v.bank_out, v.bank_in) end
                         else v.amt end as a
          from v
         where (l is null or v.has_l)
           and (coalesce(p_party, '') = '' or lower(v.party) like '%' || lower(p_party) || '%' or lower(v.ledgers) like '%' || lower(p_party) || '%')
           and (coalesce(p_vtype, '') = '' or lower(v.vtype) like '%' || lower(p_vtype) || '%')
           and (coalesce(p_text, '') = '' or lower(v.narration) like '%' || lower(p_text) || '%')
           and (mode not in ('cash', 'bank') or (mode = 'cash' and (case when dir like 'pay%' then v.cash_out when dir like 'rec%' then v.cash_in else v.cash_out + v.cash_in end) > 0)
                                             or (mode = 'bank' and (case when dir like 'pay%' then v.bank_out when dir like 'rec%' then v.bank_in else v.bank_out + v.bank_in end) > 0))
           and (mode in ('cash', 'bank') or dir = 'any' or (dir like 'pay%' and lower(v.vtype) like '%payment%') or (dir like 'rec%' and lower(v.vtype) like '%receipt%'))),
  g as (select * from f where (p_min is null or f.a >= p_min) and (p_max is null or f.a <= p_max)),
  shown as (select * from g order by g.day, g.vno, g.guid limit least(greatest(coalesce(p_limit, 200), 1), 500))
  select jsonb_build_object('tool', 'entries_filter', 'title', 'Entries' || case when mode = 'cash' then ' in cash' when mode = 'bank' then ' through the bank' else '' end ||
       case when dir like 'pay%' then ' (payments)' when dir like 'rec%' then ' (receipts)' else '' end || coalesce(' over ' || to_char(p_min, 'FM99,99,99,99,990.00'), '') || coalesce(' in ' || l, ''),
    'period', jsonb_build_object('from', s.d_from, 'to', s.d_to), 'filters', jsonb_strip_nulls(jsonb_build_object('min', p_min, 'max', p_max, 'mode', mode, 'direction', dir, 'ledger', l, 'party', nullif(p_party, ''), 'vtype', nullif(p_vtype, ''), 'text', nullif(p_text, ''))),
    'count', (select count(*) from g), 'shown', (select count(*) from shown),
    'columns', jsonb_build_array(asst_col('day', 'Date', 'date'), asst_col('vtype', 'Type'), asst_col('vno', 'No.'), asst_col('party', 'Party'), asst_col('narration', 'Narration'), asst_col('amount', 'Amount', 'amount')),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('guid', x.guid, 'day', x.day, 'vtype', x.vtype, 'vno', x.vno, 'party', x.party, 'narration', left(x.narration, 120), 'amount', round(x.a, 2)) order by x.day, x.vno, x.guid) from shown x), '[]'::jsonb),
    'summary', jsonb_build_object('total', coalesce((select round(sum(a), 2) from g), 0)))
    into res;
  return res;
end $$;

-- (8) one entry by its number (and date): every line
create or replace function public.asst_voucher(p_client text, p_vno text, p_day date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_day, p_day);
  if s.bk is null then return asst_none('voucher'); end if;
  with v as (select * from tally_vouchers v where v.book_id = s.bk and v.deleted_at is null and (lower(v.vno) = lower(btrim(coalesce(p_vno, ''))) or lower(v.ref) = lower(btrim(coalesce(p_vno, ''))))
               and (p_day is null or v.day = p_day) order by v.day limit 20)
  select jsonb_build_object('tool', 'voucher', 'title', 'Entry ' || coalesce(p_vno, ''),
    'columns', jsonb_build_array(asst_col('day', 'Date', 'date'), asst_col('vtype', 'Type'), asst_col('vno', 'No.'), asst_col('ledger', 'Ledger'), asst_col('debit', 'Debit', 'amount'), asst_col('credit', 'Credit', 'amount'), asst_col('narration', 'Narration')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', v.guid, 'day', v.day, 'vtype', v.vtype || case when v.cancelled then ' (cancelled)' when v.optional then ' (optional)' else '' end, 'vno', v.vno, 'ledger', l.ledger,
        'debit', case when l.amount < 0 then round(-l.amount, 2) else 0 end, 'credit', case when l.amount > 0 then round(l.amount, 2) else 0 end, 'narration', left(v.narration, 160)) order by v.day, v.guid, l.amount), '[]'::jsonb),
    'count', (select count(*) from v))
    into res from v left join tally_lines l on l.book_id = s.bk and l.guid = v.guid;
  return res;
end $$;

-- (9) the profit and loss as MIS heads it (src/js/07-mis.js): each ledger's movement by its head, and the owner's rule for an
-- expense head that ends in credit (it shows nil, and the excess goes to Other income); profit before tax, gross profit
create or replace function public.asst_profit_loss(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('profit_and_loss'); end if;
  with led as (select * from asst_led(p_client, s.bk) where mis <> ''),
  mv as (select led.mis hd, d.ledger, sum(d.amount) * case when led.mis in ('rev', 'oth') then 1 else -1 end a from tally_ledger_day d join led on led.name = d.ledger
          where d.book_id = s.bk and d.merged_into is null and d.day between s.d_from and s.d_to group by 1, 2),
  h0 as (select hd, sum(a) t from mv group by hd),
  hx as (select h.hd, case when h.hd not in ('rev', 'oth') and h.t < 0 then 0 else h.t end t, case when h.hd not in ('rev', 'oth') and h.t < 0 then -h.t else 0 end excess from h0 h),
  names as (select * from (values (1, 'rev', 'Revenue from operations'), (2, 'oth', 'Other income'), (3, 'pur', 'Purchases'), (4, 'dir', 'Direct expenses'), (5, 'emp', 'Employee costs'),
              (6, 'exp', 'Other expenses'), (7, 'fin', 'Finance costs'), (8, 'dep', 'Depreciation'), (9, 'tax', 'Tax')) z(o, hd, label)),
  tot as (select coalesce(sum(t) filter (where hd = 'rev'), 0) rev, coalesce(sum(t) filter (where hd = 'oth'), 0) + coalesce(sum(excess), 0) oth,
            coalesce(sum(t) filter (where hd in ('pur', 'dir', 'emp', 'exp', 'fin', 'dep')), 0) expn, coalesce(sum(t) filter (where hd in ('pur', 'dir')), 0) cogs, coalesce(sum(t) filter (where hd = 'tax'), 0) tx from hx),
  rows as (select n.o, n.label, case when n.hd = 'oth' then coalesce(hx.t, 0) + (select coalesce(sum(excess), 0) from hx) else coalesce(hx.t, 0) end amt,
             coalesce((select string_agg(m.ledger || ' ' || to_char(m.a, 'FM99,99,99,99,990.00'), '; ' order by abs(m.a) desc) from (select * from mv where mv.hd = n.hd order by abs(mv.a) desc limit 4) m), '') ||
             case when coalesce(hx.excess, 0) > 0 then ' (in credit by ' || to_char(hx.excess, 'FM99,99,99,99,990.00') || ': shown nil, the excess in Other income)' when n.hd = 'oth' and (select coalesce(sum(excess), 0) from hx) > 0 then '; excess credit of expense heads ' || to_char((select sum(excess) from hx), 'FM99,99,99,99,990.00') else '' end top
             from names n left join hx on hx.hd = n.hd where hx.hd is not null or n.hd in ('rev', 'oth'))
  select jsonb_build_object('tool', 'profit_and_loss', 'title', 'Profit and loss, ' || to_char(s.d_from, 'DD-Mon-YYYY') || ' to ' || to_char(s.d_to, 'DD-Mon-YYYY'),
    'period', jsonb_build_object('from', s.d_from, 'to', s.d_to), 'basis', 'each ledger by its Tally group, as the MIS page heads it; an expense head in credit shows nil and the excess goes to Other income (the owner''s rule)',
    'columns', jsonb_build_array(asst_col('head', 'Head'), asst_col('amount', 'Amount', 'amount'), asst_col('top', 'Largest ledgers')),
    'rows', (select jsonb_agg(jsonb_build_object('head', r.label, 'amount', round(r.amt, 2), 'top', r.top) order by r.o) from rows r)
      || jsonb_build_array(jsonb_build_object('head', 'Total income', 'amount', round(t.rev + t.oth, 2), 'top', ''), jsonb_build_object('head', 'Total expenses', 'amount', round(t.expn, 2), 'top', ''),
           jsonb_build_object('head', 'Gross profit', 'amount', round(t.rev - t.cogs, 2), 'top', 'revenue less purchases and direct expenses'), jsonb_build_object('head', 'Profit before tax', 'amount', round(t.rev + t.oth - t.expn, 2), 'top', '')),
    'summary', jsonb_build_object('pbt', round(t.rev + t.oth - t.expn, 2), 'revenue', round(t.rev, 2), 'otherIncome', round(t.oth, 2), 'expenses', round(t.expn, 2), 'gross', round(t.rev - t.cogs, 2), 'tax', round(t.tx, 2)))
    into res from tot t;
  return res;
end $$;

-- (10) sales month by month (Sales Accounts), with the output tax of the month
create or replace function public.asst_sales_by_month(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('sales_by_month'); end if;
  with led as (select * from asst_led(p_client, s.bk)),
  mo as (select to_char(gs, 'YYYYMM') ym, gs::date m from generate_series(date_trunc('month', s.d_from), date_trunc('month', s.d_to), interval '1 month') gs),
  sv as (select to_char(d.day, 'YYYYMM') ym, sum(d.amount) a from tally_ledger_day d join led on led.name = d.ledger and led.sales where d.book_id = s.bk and d.day between s.d_from and s.d_to group by 1),
  g as (select to_char(e.day, 'YYYYMM') ym, sum(e.amount) a from asst_entries(s.bk, s.d_from, s.d_to) e join led on led.name = e.ledger and led.kind = 'gst' and led.side = 'output' and led.what = 'gst'
          where exists (select 1 from tally_lines x join led sl on sl.name = x.ledger and sl.income where x.book_id = s.bk and x.guid = e.guid) group by 1)
  select jsonb_build_object('tool', 'sales_by_month', 'title', 'Sales month by month', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'columns', jsonb_build_array(asst_col('month', 'Month'), asst_col('sales', 'Sales (before GST)', 'amount'), asst_col('gst', 'Output GST', 'amount')),
    'rows', jsonb_agg(jsonb_build_object('month', to_char(mo.m, 'Mon-YYYY'), 'sales', round(coalesce(sv.a, 0), 2), 'gst', round(coalesce(g.a, 0), 2)) order by mo.ym),
    'summary', jsonb_build_object('sales', round(coalesce(sum(sv.a), 0), 2), 'gst', round(coalesce(sum(g.a), 0), 2)))
    into res from mo left join sv on sv.ym = mo.ym left join g on g.ym = mo.ym;
  return res;
end $$;

-- (11) expenses by ledger (direct and indirect), largest first
create or replace function public.asst_expenses(p_client text, p_from date, p_to date, p_limit integer default 30)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('expenses'); end if;
  with led as (select * from asst_led(p_client, s.bk) where expense or purchase),
  x as (select led.name, led.parent, -sum(d.amount) a from tally_ledger_day d join led on led.name = d.ledger where d.book_id = s.bk and d.day between s.d_from and s.d_to group by 1, 2),
