-- (24) as section 43B(h): what is owed to micro and small suppliers (the MSME type in the ledger masters) for more than 45
-- days (from the date of each bill, oldest paid first)
create or replace function public.asst_msme_43bh(p_client text, p_as_on date, p_days integer default 45)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb; dd integer := least(greatest(coalesce(p_days, 45), 1), 365);
begin
  select * into s from asst_span(p_client, null, p_as_on);
  if s.bk is null then return asst_none('msme_43bh'); end if;
  with ms as (select l.name, l.msme from asst_led(p_client, s.bk) l where l.creditor and l.msme ~* 'micro|small'),
