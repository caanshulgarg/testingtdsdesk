      'byEmployee', coalesce((select jsonb_agg(jsonb_build_object('employee', z.employee, 'paid', z.a) order by z.a desc) from (select p.employee, round(sum(p.amount), 2) a from tally_salary_pays p where p.book_id = s.bk and p.gone_at is null and p.day between s.d_from and s.d_to group by 1 limit 200) z), '[]'::jsonb)))
