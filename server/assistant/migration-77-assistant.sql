-- open items of each party, oldest first (what is unpaid, aged from the entry's date, later payments set against the oldest
-- items first). p_side customers or suppliers.
create or replace function public.asst_open_items(p_client text, p_book uuid, p_side text, p_as_on date)
returns table (party text, day date, guid text, vno text, amount numeric, age integer)
language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare r record; f date; sign numeric;
begin
  select b.from_date into f from tally_books b where b.book_id = p_book;
  sign := case when p_side = 'customers' then -1 else 1 end;          -- a customer's debit (Tally negative) is owed to us
  for r in select l.name, l.open from asst_led(p_client, p_book) l where (p_side = 'customers' and l.debtor) or (p_side <> 'customers' and l.creditor) loop
    declare items jsonb := '[]'::jsonb; pay numeric := 0; it record; k integer; left_ numeric; x jsonb;
    begin
      if sign * r.open > 0 then items := items || jsonb_build_object('day', f - 1, 'guid', '', 'vno', 'opening', 'a', sign * r.open); elsif sign * r.open < 0 then pay := -sign * r.open; end if;
      for it in select v.day, v.guid, v.vno, sum(ln.amount) a from tally_lines ln join tally_vouchers v on v.book_id = ln.book_id and v.guid = ln.guid
                 where ln.book_id = p_book and ln.ledger = r.name and v.day between f and p_as_on and not v.cancelled and not v.optional and v.deleted_at is null
                 group by v.day, v.guid, v.vno order by v.day, v.vno, v.guid loop
        if sign * it.a > 0 then items := items || jsonb_build_object('day', it.day, 'guid', it.guid, 'vno', it.vno, 'a', sign * it.a); else pay := pay - sign * it.a; end if;
      end loop;
      for k in 0 .. jsonb_array_length(items) - 1 loop
        x := items->k; left_ := (x->>'a')::numeric;
        if pay >= left_ then pay := pay - left_; left_ := 0; else left_ := left_ - pay; pay := 0; end if;
        if left_ > 0.004 then
          party := r.name; day := (x->>'day')::date; guid := x->>'guid'; vno := x->>'vno'; amount := round(left_, 2); age := p_as_on - (x->>'day')::date; return next;
        end if;
      end loop;
    end;
  end loop;
end $$;

-- (13) what customers owe or suppliers are owed, aged (0-30, 31-60, 61-90, 91-180, over 180 days from the entry's date)
