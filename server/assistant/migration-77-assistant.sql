-- the TDS rules of the app (src/js/00-core.js RULE_DEFAULTS and 06-audit.js TDS_KEY): the provision of an expense ledger
-- by its name, its limits and rates
create or replace function public.asst_tds_rule(p_ledger text)
returns table (rule text, section text, rate_ind numeric, rate_oth numeric, single numeric, lim numeric, basis text)
language sql immutable as $$
  select * from (values
    ('rent_building', '194-I', 10::numeric, 10::numeric, 0::numeric, 50000::numeric, 'monthly'),
    ('professional', '194J', 10, 10, 0, 50000, 'annual'),
    ('technical', '194J', 2, 2, 0, 50000, 'annual'),
    ('commission', '194H', 2, 2, 0, 20000, 'annual'),
    ('contractor', '194C', 1, 2, 30000, 100000, 'single_or_annual'),
    ('interest', '194A', 10, 10, 0, 10000, 'annual')) r(rule, section, rate_ind, rate_oth, single, lim, basis)
  where r.rule = case
    when p_ledger ~* 'RENT' then 'rent_building'
    when p_ledger ~* 'LEGAL|AUDIT|PROFESSIONAL|PROFF|CONSULT|ADVOCATE|RETAINER' then 'professional'
    when p_ledger ~* 'TECHNICAL' then 'technical'
    when p_ledger ~* 'COMMISSION|BROKERAGE' then 'commission'
    when p_ledger ~* 'CONTRACT|LABOUR|JOB\s*WORK|MANPOWER|TRANSPORT|FREIGHT|CARTAGE|REPAIR|MAINTENANCE|ADVERT|PRINTING|CATERING|SECURITY|HOUSEKEEPING' then 'contractor'
    when p_ledger ~* 'INTEREST' then 'interest' end
$$;

-- (15) suppliers that crossed a TDS limit with no TDS in the books (the audit's rule, src/js/06-audit.js tdsMissed): expenses
-- booked to a supplier (a Sundry Creditors line credited on the same entry), the provision by the expense ledger's name,
-- the limit for the year (or one bill, or a month for rent); a party with any TDS in the period is left out
create or replace function public.asst_tds_missed(p_client text, p_from date, p_to date, p_section text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('tds_missed'); end if;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  tdsl as (select name from led where kind in ('tds_payable', 'tds_clearing') or (kind = '' and name ~* '\mTDS\M' and duties)),
  done as (select distinct c.ledger from e c join led cl on cl.name = c.ledger and cl.creditor where exists (select 1 from e t join tdsl on tdsl.name = t.ledger where t.guid = c.guid)
           union select distinct v.party from tally_vouchers v join e t on t.guid = v.guid join tdsl on tdsl.name = t.ledger where v.book_id = s.bk),
  docs as (select e.guid, min(e.day) as day, min(e.vno) vno, min(e.vtype) vtype,
             (select c.ledger from e c join led cl on cl.name = c.ledger and cl.creditor where c.guid = e.guid and c.amount > 0 order by c.amount desc limit 1) party
             from e where e.vtype !~* 'sales' group by e.guid),
  x as (select d.party, r.rule, r.section, r.rate_ind, r.rate_oth, r.single, r.lim, r.basis, e.ledger, d.day, d.guid, d.vno, -e.amount a
          from e join docs d on d.guid = e.guid join led on led.name = e.ledger and led.expense cross join lateral asst_tds_rule(e.ledger) r
         where e.amount < 0 and d.party is not null and d.party not in (select ledger from done where ledger is not null) and d.party !~* '\mBANK\M|GOVERNMENT|MUNICIPAL|\mLIC\M'
           and (coalesce(p_section, '') = '' or upper(replace(r.section, '-', '')) = upper(replace(p_section, '-', '')))),
  agg as (select x.party, x.rule, min(x.section) as section, min(x.rate_ind) ri, min(x.rate_oth) ro, min(x.single) single, min(x.lim) lim, min(x.basis) basis, string_agg(distinct x.ledger, ', ') ledgers,
            sum(x.a) amt, max(x.a) mx, (select max(t) from (select sum(y.a) t from x y where y.party = x.party and y.rule = x.rule group by to_char(y.day, 'YYYYMM')) z) maxm,
            (array_agg(x.guid order by x.day))[1] guid, min(x.day) as day, (array_agg(x.vno order by x.day))[1] vno, count(distinct x.guid) n from x group by x.party, x.rule),
  hit as (select a.*, (select l.pan from led l where l.name = a.party) pan from agg a
           where case a.basis when 'single_or_annual' then a.mx > a.single or a.amt > a.lim when 'monthly' then a.maxm > a.lim else a.amt > a.lim end)
  select jsonb_build_object('tool', 'tds_missed', 'title', 'Suppliers past the TDS limit with no TDS deducted', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'the TDS provision from the expense ledger''s name, as the audit reads it; limits: 194C one bill over 30,000 or 1,00,000 in the year; 194J 50,000; 194H 20,000; 194-I 50,000 a month; 194A 10,000',
    'columns', jsonb_build_array(asst_col('party', 'Supplier'), asst_col('section', 'Section'), asst_col('ledgers', 'Booked to'), asst_col('amount', 'Expense', 'amount'), asst_col('largest', 'Largest bill', 'amount'), asst_col('rate', 'Rate %', 'pct'), asst_col('tds', 'TDS due', 'amount'), asst_col('pan', 'PAN')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', h.guid, 'day', h.day, 'vno', h.vno, 'party', h.party, 'section', h.section, 'ledgers', h.ledgers, 'amount', round(h.amt, 2), 'largest', round(h.mx, 2),
        'rate', case when h.pan = '' then 20 when substr(h.pan, 4, 1) in ('P', 'H') then h.ri else h.ro end,
        'tds', round(h.amt * (case when h.pan = '' then 20 when substr(h.pan, 4, 1) in ('P', 'H') then h.ri else h.ro end) / 100, 2), 'pan', h.pan) order by h.amt desc, h.party), '[]'::jsonb),
    'summary', jsonb_build_object('parties', count(*), 'amount', round(coalesce(sum(h.amt), 0), 2), 'disallowance30pct', round(coalesce(sum(h.amt), 0) * 0.3, 2)))
    into res from hit h;
  return res;
end $$;

-- the TDS deducted month by month and when it was paid. A payment is a debit to the TDS ledger on an entry with a bank
-- or cash line; a debit moving the TDS to another TDS ledger (a month-end account) is paid when that account is paid. Set
-- against the oldest deduction first. Due: the 7th of the next month, 30 April for March.
create or replace function public.asst_tds_paid(p_client text, p_book uuid, p_from date, p_to date)
returns table (ledger text, ym text, deducted numeric, due date, paid_on date, paid numeric, guid text, vno text, day date)
language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare f date; r record; it record; owed jsonb; pays jsonb; k integer; j integer; need numeric; take numeric; x jsonb; pay_l text[]; clr_l text[]; cash_l text[];
begin
  select b.from_date into f from tally_books b where b.book_id = p_book;
  select coalesce(array_agg(l.name) filter (where not (l.kind = 'tds_clearing' or l.name ~* 'MONTH\s*END|CLEARING')), '{}'), coalesce(array_agg(l.name) filter (where l.kind = 'tds_clearing' or l.name ~* 'MONTH\s*END|CLEARING'), '{}')
    into pay_l, clr_l from asst_led(p_client, p_book) l where l.kind in ('tds_payable', 'tds_clearing') or (l.kind = '' and l.duties and l.name ~* '\mTDS\M');
  select coalesce(array_agg(l.name), '{}') into cash_l from asst_led(p_client, p_book) l where l.bank or l.cash;
  -- the dates each clearing account was paid, oldest first (from the bank)
  for r in select unnest(pay_l) as name loop
    owed := '[]'::jsonb; pays := '[]'::jsonb;
    -- the opening owed counts as deducted the day before the books begin (due on its own month's rule)
    if (select coalesce(l.open, 0) from tally_ledgers l where l.book_id = p_book and l.name = r.name) > 0 then
      owed := owed || jsonb_build_object('day', f - 1, 'a', (select l.open from tally_ledgers l where l.book_id = p_book and l.name = r.name), 'guid', '', 'vno', 'opening');
    end if;
    for it in select v.day, v.guid, v.vno, sum(ln.amount) a,
                     bool_or(exists (select 1 from tally_lines z where z.ledger = any(cash_l) and z.book_id = p_book and z.guid = v.guid)) bank,
                     (select z.ledger from tally_lines z where z.ledger = any(clr_l) and z.book_id = p_book and z.guid = v.guid and z.amount > 0 limit 1) moved_to
                from tally_lines ln join tally_vouchers v on v.book_id = ln.book_id and v.guid = ln.guid
               where ln.book_id = p_book and ln.ledger = r.name and v.day between f and p_to and not v.cancelled and not v.optional and v.deleted_at is null
               group by v.day, v.guid, v.vno order by v.day, v.vno, v.guid loop
      if it.a > 0 then owed := owed || jsonb_build_object('day', it.day, 'a', it.a, 'guid', it.guid, 'vno', it.vno);
      else
        if it.bank then pays := pays || jsonb_build_object('day', it.day, 'a', -it.a, 'guid', it.guid, 'vno', it.vno);
        elsif it.moved_to is not null then
          -- paid when the clearing account is next paid from the bank, on or after the move
          pays := pays || coalesce((select jsonb_build_object('day', v2.day, 'a', -it.a, 'guid', v2.guid, 'vno', v2.vno) from tally_lines z join tally_vouchers v2 on v2.book_id = z.book_id and v2.guid = z.guid
                    where z.book_id = p_book and z.ledger = it.moved_to and z.amount < 0 and v2.day >= it.day and v2.day <= p_to and not v2.cancelled and not v2.optional and v2.deleted_at is null
                      and exists (select 1 from tally_lines b where b.ledger = any(cash_l) and b.book_id = p_book and b.guid = v2.guid)
                    order by v2.day limit 1), '[]'::jsonb);
        else pays := pays || jsonb_build_object('day', it.day, 'a', -it.a, 'guid', it.guid, 'vno', it.vno);
        end if;
      end if;
    end loop;
    -- set payments against the oldest deductions, month by month
    j := 0;
    for k in 0 .. jsonb_array_length(owed) - 1 loop
      x := owed->k; need := (x->>'a')::numeric;
      ledger := r.name; ym := to_char((x->>'day')::date, 'YYYYMM'); deducted := need; guid := x->>'guid'; vno := x->>'vno'; day := (x->>'day')::date;
      due := case when extract(month from (x->>'day')::date) = 3 then make_date(extract(year from (x->>'day')::date)::int, 4, 30)
                  else (date_trunc('month', (x->>'day')::date) + interval '1 month')::date + 6 end;
      paid_on := null; paid := 0;
      while need > 0.004 and j < jsonb_array_length(pays) loop
        take := least(need, (pays->j->>'a')::numeric);
        need := need - take; paid := paid + take; paid_on := (pays->j->>'day')::date;
        pays := jsonb_set(pays, array[j::text, 'a'], to_jsonb((pays->j->>'a')::numeric - take));
        if (pays->j->>'a')::numeric <= 0.004 then j := j + 1; end if;
      end loop;
      if need > 0.004 then paid_on := null; end if;
      if (x->>'day')::date between p_from and p_to or (x->>'day')::date < p_from and (paid_on is null or paid_on >= p_from) then return next; end if;
    end loop;
  end loop;
end $$;

-- (16) TDS paid late or not yet paid, each deduction against its due date
create or replace function public.asst_tds_late(p_client text, p_from date, p_to date)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('tds_late'); end if;
  with t as (select x.*, case when x.paid_on is null then case when x.due < s.d_to then 'not paid, overdue' else 'not yet due' end
                              when x.paid_on > x.due then 'paid late' else 'paid on time' end st from asst_tds_paid(p_client, s.bk, s.d_from, s.d_to) x)
  select jsonb_build_object('tool', 'tds_late', 'title', 'TDS deducted, when due and when paid', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'basis', 'due on the 7th of the next month (30 April for March); payments set against the oldest deduction first; a transfer to a month-end TDS account is paid when that account is paid from the bank',
    'columns', jsonb_build_array(asst_col('ledger', 'TDS ledger'), asst_col('day', 'Deducted on', 'date'), asst_col('vno', 'No.'), asst_col('amount', 'TDS', 'amount'), asst_col('due', 'Due', 'date'), asst_col('paid_on', 'Paid on', 'date'), asst_col('late', 'Days late', 'int'), asst_col('status', 'Status')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('guid', nullif(t.guid, ''), 'day', t.day, 'vno', t.vno, 'ledger', t.ledger, 'amount', round(t.deducted, 2), 'due', t.due, 'paid_on', t.paid_on,
        'late', case when t.paid_on is not null and t.paid_on > t.due then t.paid_on - t.due when t.paid_on is null and t.due < s.d_to then s.d_to - t.due else 0 end, 'status', t.st) order by t.day, t.ledger), '[]'::jsonb),
    'summary', jsonb_build_object('late', count(*) filter (where t.st = 'paid late'), 'lateAmount', round(coalesce(sum(t.deducted) filter (where t.st = 'paid late'), 0), 2),
       'overdue', count(*) filter (where t.st = 'not paid, overdue'), 'overdueAmount', round(coalesce(sum(t.deducted) filter (where t.st = 'not paid, overdue'), 0), 2)))
    into res from t;
  return res;
end $$;

-- (17) TDS by deductee: the TDS credited on each party's entries and the amount it was deducted on (the expense lines
-- of the same entries), by TDS ledger; with the PAN in Tally
create or replace function public.asst_tds_deductees(p_client text, p_from date, p_to date, p_section text)
returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s record; res jsonb;
begin
  select * into s from asst_span(p_client, p_from, p_to);
  if s.bk is null then return asst_none('tds_deductees'); end if;
  with led as (select * from asst_led(p_client, s.bk)), e as (select * from asst_entries(s.bk, s.d_from, s.d_to)),
  tl as (select name, section from led where kind = 'tds_payable' or (kind = '' and duties and name ~* '\mTDS\M')),
  t as (select e.guid, e.ledger tds_ledger, coalesce(nullif(tl.section, ''), substring(upper(e.ledger) from '19[0-9]+[A-Z]*'), '') sec, e.amount tds,
          coalesce(nullif((select v.party from tally_vouchers v where v.book_id = s.bk and v.guid = e.guid), ''), '') party
          from e join tl on tl.name = e.ledger where e.amount > 0
           and not exists (select 1 from e o join tl o2 on o2.name = o.ledger where o.guid = e.guid and o.amount < 0)),   -- not a transfer between TDS ledgers
  g as (select t.*, (select -sum(x.amount) from e x join led xl on xl.name = x.ledger and (xl.expense or xl.purchase or xl.fixed) where x.guid = t.guid and x.amount < 0) base from t),
  p as (select g.party, g.sec, g.tds_ledger, sum(g.tds) tds, sum(coalesce(g.base, 0)) base, count(*) n, (array_agg(g.guid order by g.guid))[1] guid from g
         where coalesce(p_section, '') = '' or upper(replace(g.sec, '-', '')) = upper(replace(p_section, '-', '')) group by 1, 2, 3)
  select jsonb_build_object('tool', 'tds_deductees', 'title', 'TDS by deductee', 'period', jsonb_build_object('from', s.d_from, 'to', s.d_to),
    'columns', jsonb_build_array(asst_col('party', 'Deductee'), asst_col('pan', 'PAN'), asst_col('section', 'Section'), asst_col('ledger', 'TDS ledger'), asst_col('base', 'Amount paid or credited', 'amount'), asst_col('tds', 'TDS', 'amount'), asst_col('n', 'Entries', 'int')),
    'rows', coalesce(jsonb_agg(jsonb_build_object('party', p.party, 'pan', coalesce((select l.pan from led l where l.name = p.party), ''), 'section', p.sec, 'ledger', p.tds_ledger, 'base', round(p.base, 2), 'tds', round(p.tds, 2), 'n', p.n) order by p.sec, p.tds desc, p.party), '[]'::jsonb),
    'summary', jsonb_build_object('tds', round(coalesce(sum(p.tds), 0), 2), 'deductees', count(distinct p.party)))
    into res from p;
  return res;
end $$;

-- (18) GST month by month: output, input, reverse charge (tally_gst_summary: the GST page's ledgers as confirmed)
create or replace function public.asst_gst_summary(p_client text, p_from date, p_to date)
