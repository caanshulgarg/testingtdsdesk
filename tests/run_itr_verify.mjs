// node tests/run_itr_verify.mjs - the CA's checks (app/src/lib/itr/verify.js) on the made-up client of itr_demo.mjs:
// each check Matched when the two sides agree to the rupee, and a fault planted in one side found as a Difference of
// exactly that amount with both sides and their sources; what is not there is Missing data; what FinCom cannot know is
// Needs you; and the gate: the JSON only when the schema passes, both computations agree and nothing is open.
import { importsOf, buildModel } from "../app/src/lib/itr/model.js";
import { compute } from "../app/src/lib/itr/tax.js";
import { verify, gate } from "../app/src/lib/itr/verify.js";
import { demo } from "./itr_demo.mjs";

let fails = 0;
const ok = (c, w) => { console.log((c ? "  ok   " : "  FAIL ") + w); if (!c) fails++; };
const cp = (x) => JSON.parse(JSON.stringify(x));
const D0 = await demo("ITR-3");
function run(mut = {}) {
  const D = cp(D0);
  if (mut.demo) mut.demo(D);
  const files = Object.entries(D.booksObj.itr).filter(([, v]) => v && v.kind).map(([k, v]) => Object.assign({ id: k }, v));
  if (mut.files) mut.files(files);
  const imports = importsOf(files), state = Object.assign({}, D.booksObj.itr["2026|state"], mut.state || {});
  const model = buildModel({ entity: mut.entity || D.client.entity, client: D.client, state, books: D.books, imports });
  if (mut.model) mut.model(model);
  const comp = compute(model);
  if (mut.comp) mut.comp(comp);
  const ctx = { model, main: comp, imports, books: Object.assign({}, D.books, { plPbt: mut.plPbt != null ? mut.plPbt : D.plPbt, opening: "opening" in mut ? mut.opening : D.opening }), gst: mut.gst || D.gst, tds: mut.tds || D.tds,
    form3cd: mut.form3cd || null, pfInBooks: true, pfBooks: D.books.sched.pl.pf.cy, pf36va: model.pf36va, accepted: mut.accepted || {} };
  const cs = verify(ctx), by = (id) => cs.find((c) => c.id === id) || { status: "absent" };
  return { cs, by, comp, model };
}
